import { describe, expect, it } from "vitest";
import {
  buildTableGrid,
  detectColumns,
  diffGrids,
  groupIntoRows,
  type TextBox,
} from "@/lib/pdf/tableGrid";

/**
 * Слово с рамкой. Ширина по умолчанию пропорциональна длине текста — так
 * рамки ведут себя и в реальном извлечении, а тесту не приходится считать её
 * руками в каждой строке.
 */
function box(text: string, x: number, y: number, width?: number, height = 10): TextBox {
  return { text, x, y, width: width ?? text.length * 5, height };
}

describe("groupIntoRows", () => {
  it("собирает слова одной строки независимо от порядка в потоке", () => {
    // Порядок намеренно перепутан: в PDF элементы не обязаны идти по чтению.
    const rows = groupIntoRows([
      box("бульдозер", 120, 100),
      box("1 339,47", 400, 100),
      box("91.01.01-035", 20, 100),
      box("драглайн", 120, 130),
      box("91.01.05-128", 20, 130),
    ]);

    expect(rows).toHaveLength(2);
    expect(rows[0]?.map((item) => item.text)).toEqual([
      "91.01.01-035",
      "бульдозер",
      "1 339,47",
    ]);
    expect(rows[1]?.map((item) => item.text)).toEqual(["91.01.05-128", "драглайн"]);
  });

  it("держит в одной строке слова разного кегля", () => {
    // Номер позиции мельче наименования, верхние края не совпадают, но
    // середины лежат на одной линии — строка одна.
    const rows = groupIntoRows([
      box("1", 20, 103, 5, 6),
      box("Разработка грунта", 60, 100, 90, 12),
    ]);

    expect(rows).toHaveLength(1);
    expect(rows[0]).toHaveLength(2);
  });

  it("пустые слова не создают строк", () => {
    expect(groupIntoRows([box("   ", 20, 100), box("", 40, 300)])).toEqual([]);
  });

  it("без слов возвращает пустой список, а не падает", () => {
    expect(groupIntoRows([])).toEqual([]);
  });
});

describe("detectColumns", () => {
  it("находит границы по пустым полосам, а не по левым краям", () => {
    /*
      Колонка чисел выровнена по правому краю: левые края 360, 380 и 390
      разные, но пустая полоса перед ней одна и та же. Кластеризация по левому
      краю развалила бы эту колонку на три.
    */
    const columns = detectColumns([
      box("код", 20, 100, 40),
      box("1 339,47", 360, 100, 60),
      box("код", 20, 120, 40),
      box("88,75", 380, 120, 40),
      box("код", 20, 140, 40),
      box("4,50", 390, 140, 30),
    ]);

    expect(columns).toHaveLength(2);
    expect(columns[0]?.left).toBe(20);
    expect(columns[1]?.right).toBe(420);
  });

  it("не режет колонку по промежутку между словами внутри ячейки", () => {
    // «Разработка» и «грунта» разделены обычным пробелом — это одна ячейка.
    const columns = detectColumns([
      box("Разработка", 60, 100, 50),
      box("грунта", 114, 100, 30),
      box("1 200", 400, 100, 30),
    ]);

    expect(columns).toHaveLength(2);
  });

  it("одна колонка остаётся одной", () => {
    const columns = detectColumns([box("итого", 20, 100), box("по разделу", 20, 120)]);
    expect(columns).toHaveLength(1);
  });

  it("без слов колонок нет", () => {
    expect(detectColumns([])).toEqual([]);
  });
});

describe("buildTableGrid", () => {
  const TABLE: readonly TextBox[] = [
    box("Код", 20, 40, 30),
    box("Наименование", 120, 40, 80),
    box("Цена", 400, 40, 30),

    box("91.01.01-035", 20, 100, 70),
    box("Бульдозер", 120, 100, 55),
    box("1 339,47", 390, 100, 40),

    box("91.01.05-128", 20, 130, 70),
    box("Драглайн", 120, 130, 50),
    box("88 134,75", 385, 130, 45),
  ];

  it("раскладывает таблицу по строкам и колонкам", () => {
    const grid = buildTableGrid(TABLE);

    expect(grid.columns).toHaveLength(3);
    expect(grid.rows).toEqual([
      ["Код", "Наименование", "Цена"],
      ["91.01.01-035", "Бульдозер", "1 339,47"],
      ["91.01.05-128", "Драглайн", "88 134,75"],
    ]);
  });

  it("склеивает куски ячейки по расстоянию, а не через пробел подряд", () => {
    /*
      «1 339,47» приезжает тремя кусками. Между «1» и «339,» стоит настоящий
      пробел разряда, между «339,» и «47» — только кернинг. Склейка через
      пробел подряд дала бы «1 339, 47»: число, которое не разберёт parseFloat
      и которое при сверке двух разборов выглядит расхождением, хотя разобрано
      верно.
    */
    const grid = buildTableGrid([
      box("Код", 20, 40, 30),
      box("Цена", 400, 40, 30),
      box("91.01.01-035", 20, 100, 70),
      box("1", 390, 100, 6),
      box("339,", 402, 100, 20),
      box("47", 422, 100, 12),
    ]);

    expect(grid.rows[1]?.[1]).toBe("1 339,47");
  });

  it("пустая ячейка остаётся пустой строкой, а не сдвигает соседей", () => {
    const grid = buildTableGrid([
      box("Код", 20, 40, 30),
      box("Наименование", 120, 40, 80),
      box("Цена", 400, 40, 30),
      box("91.01.01-035", 20, 100, 70),
      // Наименования нет — цена обязана остаться в своей колонке.
      box("1 339,47", 390, 100, 40),
    ]);

    expect(grid.rows[1]).toEqual(["91.01.01-035", "", "1 339,47"]);
  });

  it("отмечает строку, где слово накрыло несколько колонок", () => {
    /*
      Заголовок над группой колонок. Разрезать его по границе нельзя: получилось
      бы три обрывка, каждый из которых выглядит как подпись своей колонки.
      Поэтому слово кладётся в одну колонку, а строка помечается.
    */
    const grid = buildTableGrid([
      box("Индексы к элементам прямых затрат", 20, 40, 400),
      box("ОТ", 20, 70, 20),
      box("ЭМ", 200, 70, 20),
      box("МАТ", 390, 70, 30),
      box("1,09", 20, 100, 25),
      box("1,15", 200, 100, 25),
      box("1,22", 390, 100, 25),
    ]);

    expect(grid.spanningRows).toEqual([0]);
    expect(grid.rows[2]).toEqual(["1,09", "1,15", "1,22"]);
  });

  it("без слов отдаёт пустую сетку, а не падает", () => {
    expect(buildTableGrid([])).toEqual({ rows: [], columns: [], spanningRows: [] });
  });
});

describe("diffGrids", () => {
  const LEFT = buildTableGrid([
    box("код", 20, 100, 30),
    box("1,09", 400, 100, 25),
  ]);

  it("одинаковые разборы расхождений не дают", () => {
    expect(diffGrids(LEFT, LEFT)).toEqual([]);
  });

  it("находит съехавшую цифру — ту ошибку, которую не ловит проверка диапазона", () => {
    const right = buildTableGrid([
      box("код", 20, 100, 30),
      box("1,90", 400, 100, 25),
    ]);

    expect(diffGrids(LEFT, right)).toEqual([
      { row: 0, column: 1, left: "1,09", right: "1,90" },
    ]);
  });

  it("не считает расхождением разную расстановку пробелов", () => {
    const right = buildTableGrid([
      box("код", 20, 100, 30),
      box("1,", 400, 100, 12),
      box("09", 413, 100, 12),
    ]);

    expect(diffGrids(LEFT, right)).toEqual([]);
  });

  it("разный размер сетки — тоже расхождение, а не исключение", () => {
    // Лишняя строка справа возвращается ячейками с пустой левой стороной,
    // чтобы у человека был один список расхождений, а не два разных отчёта.
    const right = buildTableGrid([
      box("код", 20, 100, 30),
      box("1,09", 400, 100, 25),
      box("лишняя", 20, 130, 35),
    ]);

    expect(diffGrids(LEFT, right)).toEqual([
      { row: 1, column: 0, left: "", right: "лишняя" },
    ]);
  });
});
