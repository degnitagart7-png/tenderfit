/** Сверка с профилем, как её посчитал разбор: те же статусы и причины, что в исходном отчёте. */
export function profileMatch377(): ProfileMatch {
  const order: Record<ProfileCheckStatus, number> = { NOT_MET: 0, CHECK: 1, MET: 2 };
  const checks = REQUIREMENTS.map((r) => ({
    finding: r.finding,
    kind: inferRequirementKind(r.finding),
    status: r.status,
    reason: r.reason,
  })).sort((a, b) => order[a.status] - order[b.status]);
  const met = checks.filter((c) => c.status === "MET").length;
  const toCheck = checks.filter((c) => c.status === "CHECK").length;
  return {
    verdict: "REVIEW",
    headline: `Препятствий не найдено, сверить вручную: ${String(toCheck)}`,
    checks,
    met,
    notMet: 0,
    toCheck,
  };
}

