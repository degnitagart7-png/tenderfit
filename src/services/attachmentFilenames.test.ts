import { describe, expect, it } from "vitest";
import { uniqueFilenames } from "@/services/attachmentFilenames";

/**
 * Имена файлов для записи в tender_documents.
 *
 * У ЕИС уникальность имён обеспечивает обход вкладки документов, а у площадки и
 * у агрегатора имя приходит от источника и может повториться: части одного
 * архива и тома одного лота заказчики называют одинаково. Повтор перезаписал бы
 * чужую строку — в базе ключ `(tender_id, filename)`, — поэтому дубликаты
 * получают номер по порядку.
 */
describe("uniqueFilenames", () => {
  it("уникальные имена оставляет как есть", () => {
    expect(uniqueFilenames(["Извещение.docx", "Проект договора.pdf"])).toEqual([
      "Извещение.docx",
      "Проект договора.pdf",
    ]);
  });

  it("повторяющееся имя получает номер перед расширением", () => {
    expect(uniqueFilenames(["Описание.docx", "Описание.docx", "Описание.docx"])).toEqual([
      "Описание (1).docx",
      "Описание (2).docx",
      "Описание (3).docx",
    ]);
  });

  it("сравнивает имена без учёта регистра", () => {
    // Расширение в пронумерованном имени приводится к нижнему регистру: его
    // печатает fileExtension, а он же определяет формат. На разбор это не
    // влияет — detectFileType всё равно сравнивает в нижнем регистре, — зато
    // «Описание.DOCX» и «описание.docx» не выглядят в карточке двумя разными
    // файлами.
    expect(uniqueFilenames(["Описание.DOCX", "описание.docx"])).toEqual([
      "Описание (1).docx",
      "описание (2).docx",
    ]);
  });

  it("имя без расширения получает номер в конце", () => {
    expect(uniqueFilenames(["README", "README"])).toEqual(["README (1)", "README (2)"]);
  });

  it("пустой список остаётся пустым", () => {
    expect(uniqueFilenames([])).toEqual([]);
  });
});
