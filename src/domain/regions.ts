/** Полный словарь: субъекты и их административные центры. */
const REGION_DICTIONARY: readonly RegionAliases[] = [...RF_REGIONS, ...REGION_CAPITALS];

/**
 * Приведение к форме, в которой хранится словарь: нижний регистр, «ё» → «е»,
 * любая пунктуация и пробелы — один пробел. «Ханты-Мансийский АО — Югра» и
 * «Ханты Мансийский АО Югра» после этого неотличимы.
 */
export function normalizeRegionText(value: string): string {
  return value
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[^0-9a-zа-я]+/g, " ")
    .trim();
}

interface BucketEntry {
  alias: string;
  canonical: string;
}

/**
 * Падежные формы варианта: в названиях закупок субъект почти всегда стоит не в
 * именительном падеже — «на АЗС, расположенных в Белгородской области», «для нужд
 * Краснодарского края», «Ямало-Ненецкого автономного округа». Без них определение
 * региона по названию промахивалось и брало запасной адрес — у площадок это часто
 * офис организатора в другом городе.
 *
 * Склоняется только сочетание со словом «область»/«край»/«автономный округ», не голое
 * прилагательное: «Белгородской» в одиночку — это и «ул. Белгородской», и словарь
 * такую форму не получает.
 */
function inflectedAliases(alias: string): string[] {
  const oblast = /^([а-я]+)ая (область|обл)$/.exec(alias);
  if (oblast) {
    const [, stem, word] = oblast;
    return word === "обл"
      ? [`${stem}ой обл`]
      : [`${stem}ой области`, `${stem}ую область`];
  }
  const krai = /^([а-я]+)ий край$/.exec(alias);
  if (krai) {
    const stem = krai[1];
    return [`${stem}ого края`, `${stem}ом крае`, `${stem}ому краю`];
  }
  const okrug = /^([а-я ]+?)ий автономный округ$/.exec(alias);
  if (okrug) {
    const stem = okrug[1];
    return [`${stem}ого автономного округа`, `${stem}ом автономном округе`];
  }
  return [];
}

/**
 * Словарь по первой букве варианта, внутри — от длинных вариантов к коротким.
 * Так «Алтайский край» находится раньше, чем «Алтай», и «Московская область» —
 * раньше, чем «Москва».
 */
const BUCKETS: ReadonlyMap<string, readonly BucketEntry[]> = (() => {
  const buckets = new Map<string, BucketEntry[]>();
  for (const region of REGION_DICTIONARY) {
    for (const raw of region.aliases) {
      const base = normalizeRegionText(raw);
      if (!base) continue;
      for (const alias of [base, ...inflectedAliases(base)]) {
        const first = alias[0];
        if (!first) continue;
        const bucket = buckets.get(first) ?? [];
        bucket.push({ alias, canonical: region.canonical });
        buckets.set(first, bucket);
      }
    }
  }
  for (const bucket of buckets.values()) {
    bucket.sort((a, b) => b.alias.length - a.alias.length || a.alias.localeCompare(b.alias));
  }
  return buckets;
})();

/** Все канонические наименования субъектов — для справок и подсказок в UI. */
export const CANONICAL_REGIONS: readonly string[] = RF_REGIONS.map((region) => region.canonical);

/**
 * Субъект РФ по свободному тексту (адрес поставки, наименование места).
 * Возвращает каноническое наименование либо `UNKNOWN_REGION`, если совпадения
 * нет: неизвестный регион — это неопределённость, а не «другой регион».
 *
 * Побеждает самое раннее совпадение, а на одной позиции — самое длинное:
 * в адресах субъект идёт первым, а «Башкортостан Респ» важнее «Башкортостан».
 */
export function regionFromAddress(text: string | null | undefined): string {
  const haystack = normalizeRegionText(text ?? "");
  if (!haystack) return UNKNOWN_REGION;

  let best: { index: number; length: number; canonical: string } | null = null;
  for (let index = 0; index < haystack.length; index += 1) {
    // Совпадение раньше уже найденного невозможно: индекс только растёт.
    if (best !== null && best.index < index) break;
    const previous = index > 0 ? haystack[index - 1] : undefined;
    if (previous !== undefined && WORD_CHAR.test(previous)) continue;

    const bucket = BUCKETS.get(haystack[index] as string);
    if (!bucket) continue;
    for (const entry of bucket) {
      if (!haystack.startsWith(entry.alias, index)) continue;
      const end = index + entry.alias.length;
      const next = end < haystack.length ? haystack[end] : undefined;
      // «Алтай» внутри «Алтайский» — не совпадение: дальше буква.
      if (next !== undefined && WORD_CHAR.test(next)) continue;
      best = { index, length: entry.alias.length, canonical: entry.canonical };
      break; // в корзине варианты уже отсортированы по убыванию длины
    }
  }
  return best === null ? UNKNOWN_REGION : best.canonical;
}

/**
 * Регион по нескольким местам поставки: берётся первое распознанное значение.
 * Порядок важен — у совместных закупок первым идёт основной регион.
 */
export function regionFromAddresses(values: readonly (string | null | undefined)[]): string {
  for (const value of values) {
    const region = regionFromAddress(value);
    if (region !== UNKNOWN_REGION) return region;
  }
  return UNKNOWN_REGION;
}
