describe("classifyProcurementNature", () => {
  it.each(CASES)("%s: %s", (expected, subject) => {
    expect(classifyProcurementNature({ subject })).toBe(expected);
  });

  it("«Приобретение … жилого помещения» — недвижимость даже с ОКПД2 41.20 (здания жилые)", () => {
    expect(
      classifyProcurementNature({
        subject: "Приобретение жилого помещения у застройщика",
        okpd2Codes: ["41.20.10.110"],
      }),
    ).toBe("REAL_ESTATE");
  });

  it("запрос цен без оговорок — обычная процедура 223-ФЗ, а не мониторинг", () => {
    expect(classifyProcurementNature({ subject: "Запрос цен на выполнение работ по ремонту кровли" })).not.toBe(
      "PRICE_MONITORING",
    );
  });

  it("«мониторингу цен» как услуга — не мониторинг цен", () => {
    expect(classifyProcurementNature({ subject: "Оказание услуг по мониторингу цен на рынке" })).toBe("SERVICES");
  });

  it("регистр, «ё» и номер лота в начале названия не мешают", () => {
    expect(classifyProcurementNature({ subject: "ЛОТ № 2. ПРИОБРЕТЕНИЕ ЖИЛОГО ПОМЕЩЕНИЯ" })).toBe("REAL_ESTATE");
  });

  it("по названию природа не ясна — читаются лоты, затем ОКПД2", () => {
    expect(classifyProcurementNature({ subject: "Заявка №123", lotSubjects: ["Капитальный ремонт кровли"] })).toBe(
      "WORKS",
    );
    expect(classifyProcurementNature({ subject: "Заявка №123", okpd2Codes: ["43.99.90.190"] })).toBe("WORKS");
  });
});

describe("намерение: подряд ли ищет человек", () => {
  it("слова профиля владельца — про подряд", () => {
    expect(queryIsAboutWorks(["Строительные работы", "Капитальное строительство", "Строительство"])).toBe(true);
    expect(queryIsAboutWorks(["ремонт"])).toBe(true);
  });

  it("компьютеры и вентили — нет", () => {
    expect(queryIsAboutWorks(["ноутбук", "вентиль"])).toBe(false);
  });

  it("поставщик оргтехники с монтажом сетей — не подрядчик, строительная компания — подрядчик", () => {
    expect(profileIsContractor(demoCompanyProfile)).toBe(false);
    const builder: CompanyProfile = {
      ...demoCompanyProfile,
      activityDescription: "Строительство и капитальный ремонт зданий",
    };
    expect(profileIsContractor(builder)).toBe(true);
    const byOkpd: CompanyProfile = {
      ...demoCompanyProfile,
      capabilities: { ...demoCompanyProfile.capabilities, okpd2Codes: ["43.99"] },
    };
    expect(profileIsContractor(byOkpd)).toBe(true);
  });
});

describe("подписи скрытого", () => {
  it("называет только то, что скрыто", () => {
    expect(nonContractLabel({ REAL_ESTATE: 3 })).toBe("не подряд: покупка квартир и помещений");
    expect(nonContractLabel({ REAL_ESTATE: 3, PRICE_MONITORING: 2 })).toBe(
      "не подряд: покупка квартир и помещений, мониторинг цен",
    );
    expect(nonContractLabel({ REAL_ESTATE: 0, PRICE_MONITORING: 2 })).toBe("не подряд: мониторинг цен");
  });

  it("одна причина — без числа, несколько — каждая со своим", () => {
    expect(hiddenReasonsText({ limits: 4, fit: 0, nature: {} })).toBe(" (вне профиля поиска)");
    expect(hiddenReasonsText({ limits: 0, fit: 2, nature: {} })).toBe(" (не подходят компании)");
    expect(hiddenReasonsText({ limits: 0, fit: 0, nature: { REAL_ESTATE: 5 } })).toBe(
      " (не подряд: покупка квартир и помещений)",
    );
    expect(hiddenReasonsText({ limits: 1, fit: 2, nature: { REAL_ESTATE: 5, PRICE_MONITORING: 1 } })).toBe(
      " (вне профиля поиска — 1, не подходят компании — 2, не подряд: покупка квартир и помещений, мониторинг цен — 6)",
    );
    expect(hiddenReasonsText({ limits: 0, fit: 0, nature: {} })).toBe("");
  });
});
