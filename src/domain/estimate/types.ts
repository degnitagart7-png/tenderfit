/**
 * Типы сметного расчёта по открытым данным ФГИС ЦС.
 *
 * Источник фактов — выгрузка ФСНБ-2022 (приказ Минстроя России от 12.08.2026
 * № 527/пр): нормы ГЭСН, Федеральная сметная база цен (ФСБЦ) в уровне
 * 01.01.2022, текущие сметные цены строительных ресурсов (ФСЦСР) по ценовым
 * зонам и кварталам, реестр ставок оплаты труда рабочих по разрядам.
 *
 * Разбор того, что реально отдаёт портал и где проходят границы автоматизации,
 * — в docs/REFERENCE_GRAND_SMETA.md.
 */

/**
 * Вид ресурса в норме. Определяется по коду, а не по наименованию.
 *
 * В выгрузке ИАС ЦС сосуществуют две записи труда рабочих, и они никогда не
 * встречаются в одной норме (проверено на всех 30 028 нормах «ГЭСН.xml»:
 * 23 310 норм с «1-100-*», 3 273 с «2-100-*», ни одной с обеими). Поэтому
 * деньги начисляются только по разрядным строкам, а итоговая строка «1»
 * служит справочной сверкой.
 */
export type ResourceKind =
  /**
   * Затраты труда рабочих, чел.-ч, с указанием разряда. Оцениваются по шкале
   * оплаты труда. Коды «1-100-38» (средний разряд 3,8) и «2-100-04»
   * (рабочий 4 разряда).
   */
  | "LABOUR"
  /**
   * Итоговые затраты труда рабочих, чел.-ч. Служебный код «1»; равен сумме
   * строк «2-100-*» той же нормы. В расчёте не оценивается — иначе труд
   * был бы посчитан дважды.
   */
  | "WORKER_HOURS_TOTAL"
  /**
   * Затраты труда машинистов, чел.-ч. Служебный код «2» и код звена машины
   * «4-100-060». Оплата уже внутри стоимости маш.-ч, отдельно не оценивается.
   */
  | "MACHINIST_HOURS"
  /** Машина или механизм. Код начинается с «91.». */
  | "MACHINE"
  /** Материал, изделие, конструкция или оборудование. */
  | "MATERIAL"
  /** Код не распознан. Позиция попадает в список пробелов, а не в расчёт. */
  | "UNKNOWN";

/** Один ресурс в составе нормы. */
export interface NormResource {
  readonly code: string;
  readonly kind: ResourceKind;
  /** Наименование из нормы или из классификатора; может быть пустым. */
  readonly name: string;
  readonly quantity: number;
  /** Единица измерения ресурса: «чел.-ч», «маш.-ч», «м3», «т» и т. п. */
  readonly unit: string;
  /**
   * Пометка количества, когда в выгрузке оно не число. «П» означает «по
   * проекту»: расход определяется проектной документацией, а не нормой. В
   * «ГЭСН.xml» таких 15 437, и при них quantity равен нулю.
   */
  readonly quantityNote: string | null;
  /**
   * Ресурс без конкретной марки. В выгрузке это AbstractResource (код группы,
   * например «01.7.12.16», с атрибутом TechnologyGroups) и ServiceResource
   * («999-9901», «МАТЕРИАЛЫ (см. приложение)»). Цены на такой код в
   * классификаторе нет: стоимость выбирается проектом, поэтому позиция идёт в
   * пробелы, а не в расчёт.
   */
  readonly projectSpecific: boolean;
  /** Код технологической группы из атрибута TechnologyGroups, если он есть. */
  readonly technologyGroup: string | null;
}

/** Норма ГЭСН — строка расценки, к которой привязывается объём работ. */
export interface NormRecord {
  /**
   * Полный код, например «01-01-001-01».
   *
   * Уникален только вместе с `baseType`: в выгрузке ФГИС ЦС 2 784 кода
   * встречаются больше чем в одной книге, и «01-01-001-01» — это и драглайн,
   * и токарный станок, и синхронный генератор, и замок двери шахты лифта.
   */
  readonly code: string;
  /** Код таблицы, например «01-01-001». */
  readonly tableCode: string;
  /** Наименование таблицы + окончание строки: то, что видит сметчик. */
  readonly fullName: string;
  /** Окончание строки из атрибута EndName. */
  readonly endName: string;
  /** Единица измерения нормы, например «1000 м3». */
  readonly unit: string;
  /** Код сборника, например «01». */
  readonly collectionCode: string;
  /** Наименование сборника, например «Земляные работы». */
  readonly collectionName: string;
  /** Раздел внутри сборника. */
  readonly sectionName: string;
  /** Подраздел внутри раздела. */
  readonly subsectionName: string;
  /** Тип базы: «ГЭСН», «ГЭСНм», «ГЭСНр», «ГЭСНп», «ГЭСНмр». */
  readonly baseType: string;
  /** Состав работ из блока Content — то, чем норма обосновывается. */
  readonly content: readonly string[];
  readonly resources: readonly NormResource[];
  /** Указатель на норму накладных расходов из атрибута Nr («Пр/812-001.1»). */
  readonly overheadRef: string | null;
  /** Указатель на норму сметной прибыли из атрибута Sp («Пр/774-001.1»). */
  readonly profitRef: string | null;
}

/** Откуда взялась цена ресурса. Показываем в расшифровке каждой строки. */
export type PriceSourceKind =
  /** Текущая цена ФСЦСР по ценовой зоне за конкретный квартал — основной случай. */
  | "CURRENT_ZONE"
  /** База ФСБЦ в уровне 01.01.2022 без пересчёта. Используется, когда текущей цены нет. */
  | "BASE_2022"
  /** База 01.01.2022, пересчитанная индексом Минстроя по элементу затрат. */
  | "BASE_2022_INDEXED"
  /** Ставка оплаты труда из тарифной шкалы ценовой зоны. Точность — в `wageOrigin`. */
  | "WAGE_SCALE";

/**
 * Происхождение цены в напечатанной строке сметы.
 *
 * `UNPRICED` добавлен к источникам цены, а не заменой им: строка с нулём,
 * подписанная «база 01.01.2022» или «тарифная шкала», утверждает, что источник
 * дал ноль. Это неправда — источник не дал ничего, и разница видна только так.
 * В записи цены (`ResourcePrice`) значения быть не может: у записи есть цена.
 */
export type ResourceLineSource = PriceSourceKind | "UNPRICED";

/** Цена ресурса с указанием происхождения. */
export interface ResourcePrice {
  readonly code: string;
  readonly name: string;
  readonly unit: string;
  /** Цена за единицу, ₽ без НДС. */
  readonly price: number;
  /**
   * Для машин: оплата труда машинистов, ₽ за один маш.-ч суммарно по составу
   * звена, а не на одного человека. Входит в фонд оплаты труда, а через него —
   * в накладные расходы и сметную прибыль. Для прочих ресурсов null.
   */
  readonly machinistSalary: number | null;
  /** Для машин: численность звена, чел. на маш.-ч. Для прочих — null. */
  readonly machinistHours: number | null;
  readonly source: PriceSourceKind;
  /** Период текущих цен, например «3 квартал 2026 г.». Для базы — null. */
  readonly period: string | null;
  /** Ценовая зона, например «Амурская область (1 зона)». Для базы — null. */
  readonly zone: string | null;
}

/**
 * Опорная точка тарифной шкалы: разряд и ставка за чел.-ч.
 *
 * Берётся из двух открытых источников одной ценовой зоны за один квартал:
 * реестр ставок рабочих (`1-100-*`, покрывает разряды 1,0–3,4) и колонка
 * «Оплата труда машинистов» в текущих ценах ФСЦСР (`4-100-*`, делённая на
 * численность звена — даёт разряды 2–9). Там, где источники пересекаются,
 * значения совпадают до копейки: разряд 2,0 — 598,26 ₽, разряд 3,0 — 653,14 ₽.
 */
export interface WageAnchor {
  /** Средний разряд, например 3.8. */
  readonly rank: number;
  /** Ставка, ₽ за чел.-ч. */
  readonly salary: number;
  /** Откуда взята точка: наименование реестра или выгрузки ФСЦСР. */
  readonly source: string;
}

/** Как получена ставка для разряда. Показывается в расшифровке строки сметы. */
export type WageOrigin =
  /** Точное значение из открытых данных. */
  | "ANCHOR"
  /** Линейная интерполяция между соседними разрядами шкалы. */
  | "INTERPOLATED"
  /** Продолжение шкалы за пределы известных разрядов. Приближение. */
  | "EXTRAPOLATED";

/** Тарифная шкала ценовой зоны за период. */
export interface WageScale {
  readonly region: string;
  readonly zone: string;
  readonly period: string;
  /** Опорные точки, отсортированные по разряду, без повторов. */
  readonly anchors: readonly WageAnchor[];
  /** Ставка 1-го разряда — знаменатель тарифных коэффициентов. */
  readonly baseSalary: number;
  readonly minRank: number;
  readonly maxRank: number;
}

/** Ставка оплаты труда, определённая для конкретного кода ресурса. */
export interface ResolvedWage {
  /** Код ресурса, по которому шла справка, например «1-100-38». */
  readonly code: string;
  readonly rank: number;
  /** Ставка, ₽ за чел.-ч. */
  readonly salary: number;
  readonly origin: WageOrigin;
}

/** Позиция ведомости объёмов работ — вход расчёта. */
export interface BillOfWorkItem {
  /** Устойчивый идентификатор внутри ведомости. */
  readonly id: string;
  /** Наименование работы так, как оно записано в документации. */
  readonly workName: string;
  /** Объём в единицах ведомости. */
  readonly quantity: number;
  /** Единица ведомости, например «м3». */
  readonly quantityUnit: string;
  /**
   * Делитель перевода единицы ведомости в единицу нормы. Для «м3 → 1000 м3»
   * это 1000. Если единицы совпадают, делитель равен 1. Без него расчёт
   * обязан сообщить о расхождении, а не угадать.
   */
  readonly unitDivisor: number;
  /** Код нормы, если он назначен явно. Иначе норма подбирается поиском. */
  readonly normCode: string | null;
  /**
   * Код ресурса ФСНБ, когда позиция ведомости — не работа, а поставляемый
   * материал или машина: «07.2.07.12-0068», «91.05.01-017».
   *
   * Заполнен — позиция считается прямо по справочнику цен, ценой за единицу на
   * объём, и в подбор расценки не идёт вовсе. Труда и машин у неё нет: их
   * несёт работа, в которой материал укладывают, а не сам материал.
   *
   * Почему это отдельное поле, а не догадка расчёта. Ведомость заказчика
   * перечисляет работы и материалы вперемешку, и по наименованию их не
   * различить: «Металлоконструкции … сталь С255» одинаково похоже и на
   * поставку, и на монтаж. Документ говорит об этом в колонке обоснования —
   * значит различие приходит оттуда, а не из эвристики по тексту.
   */
  readonly resourceCode: string | null;
  /**
   * Книга, в которой находится норма: «ГЭСН», «ГЭСНм», «ГЭСНр», «ГЭСНп»,
   * «ГЭСНмр». Без неё код неоднозначен.
   *
   * Перепись всех пяти книг выгрузки ФГИС ЦС даёт 56 242 элемента Work и
   * 53 228 различных кодов: 2 784 кода встречаются больше одного раза. Код
   * «01-01-001-01» означает экскаватор-драглайн в ГЭСН, токарный станок в ГЭСНм,
   * синхронный генератор в ГЭСНп и замок двери шахты лифта в ГЭСНмр. Выбрать
   * один из четырёх молча — значит посчитать земляные работы как монтаж
   * станка и получить правдоподобную смету с неверным числом.
   *
   * null допустим: тогда подбор обязан вернуть все книги, в которых код
   * найден, и пусть выбирает человек.
   */
  readonly normBaseType: string | null;
  /** Дословная цитата из документа-основания. Обязательна для объяснимости. */
  readonly sourceQuote: string | null;
  /** Имя документа, откуда взята позиция. */
  readonly sourceDocument: string | null;
}

/** Раздел сметы — grouping позиций по главам или по видам работ. */
export interface BillOfWorkSection {
  readonly title: string;
  readonly items: readonly BillOfWorkItem[];
}

/** Индексы пересчёта к текущему уровню цен. */
export interface IndexSet {
  /** Период, к которому относятся индексы, например «III квартал 2026 г.». */
  readonly period: string;
  /** Индекс к оплате труда рабочих. */
  readonly labour: number;
  /**
   * Индекс к оплате труда машинистов.
   *
   * Отдельный от индекса рабочих, потому что Минстрой публикует его отдельной
   * колонкой: внутри индекса к эксплуатации машин оплата труда машинистов
   * выделена как «в том числе ОТм» и пересчитывается своим значением. Считать
   * её индексом рабочих значило бы подставить чужое число в базу накладных
   * расходов и сметной прибыли.
   */
  readonly machinistLabour: number;
  /**
   * Индекс к стоимости эксплуатации машин — без учёта оплаты труда машинистов.
   *
   * Цена маш.-ч в базе полная: «без зарплаты» плюс зарплата звена. Индексом
   * машин пересчитывается только первая часть, вторая идёт по `machinistLabour`,
   * иначе одна и та же зарплата оказалась бы пересчитана двумя разными
   * индексами — одним внутри стоимости машин, другим в фонде оплаты труда.
   */
  readonly machines: number;
  /** Индекс к стоимости материалов. */
  readonly materials: number;
  /** Откуда взяты индексы: реквизиты письма Минстроя или отметка о ручном вводе. */
  readonly source: string;
}

/**
 * Нормативы накладных расходов и сметной прибыли, % от фонда оплаты труда.
 *
 * Это резерв на весь документ, а не основной путь. Нормативы привязаны к
 * расценке: каждая норма несёт указатели `Nr` и `Sp` (`overheadRef`,
 * `profitRef`), и правильный норматив берётся по ним из `overheadRates`
 * ценовой книги. Сюда расчёт опускается, только когда указателя нет или он не
 * найден в справочнике, и всегда с пометкой `NO_OVERHEAD_RATE`.
 */
export interface OverheadRates {
  readonly overheadPercent: number;
  readonly profitPercent: number;
  /** Наименование вида работ, к которому применён норматив. */
  readonly workType: string;
  readonly source: string;
}

/**
 * Один норматив НР или СП из приказов Минстроя, найденный по указателю нормы.
 *
 * Ключ — то, что лежит в самих данных ФСНБ: `<ReasonItem Nr="Пр/812-001.1"
 * Sp="Пр/774-001.1"/>`. Приказ 812/пр задаёт накладные расходы, 774/пр —
 * сметную прибыль, поэтому префикс указателя сам говорит, к какому из двух
 * начислений относится строка, и одной таблицы на оба вида достаточно.
 */
export interface OverheadRate {
  /** Указатель из нормы, например «Пр/812-001.1». */
  readonly ref: string;
  /** Норматив, % от фонда оплаты труда. */
  readonly percent: number;
  /** Вид работ, к которому приказ относит норматив. */
  readonly workType: string;
  /** Реквизиты приказа и пункта таблицы. */
  readonly source: string;
}

/**
 * Откуда взят норматив, применённый к позиции.
 *
 * Печатается в строке: смета, где НР начислены резервом документа, и смета,
 * где они начислены по виду работ расценки, — это два разных документа, и
 * разница обязана быть видна без чтения списка пометок.
 */
export type OverheadRateSource =
  /** Найден по указателю нормы — основной случай. */
  | "NORM_REF"
  /** Указателя нет или он не найден: взят резерв документа. */
  | "DEFAULT"
  /**
   * Норматива нет и быть не должно: позиция — поставка материала или машины.
   *
   * Отдельно от «DEFAULT», потому что «взят резерв» и «начислять нечего» —
   * разные утверждения. Первое требует проверки сметчиком, второе нет, и
   * метрика допущений обязана их различать.
   */
  | "NONE";

/** Лимитированные затраты, % от стоимости строительно-монтажных работ. */
export interface LimitedCosts {
  /** Зимнее удорожание, ГСН 81-05-02. */
  readonly winterSurchargePercent: number;
  /** Временные здания и сооружения, ГСН 81-05-01. */
  readonly temporaryStructuresPercent: number;
  readonly source: string;
}

/** Все внешние параметры расчёта. Передаются явно, ничего не читается извне. */
export interface EstimateParameters {
  readonly vatPercent: number;
  /**
   * null — расчёт идёт строго по текущим ценам ФСЦСР, индекс не применяется.
   * Значение нужно, когда часть ресурсов отсутствует в текущих ценах и их
   * приходится пересчитывать от базы 01.01.2022.
   */
  readonly indices: IndexSet | null;
  readonly overhead: OverheadRates;
  readonly limited: LimitedCosts;
}

/** Одна ресурсная строка в расшифровке позиции сметы. */
export interface EstimateResourceLine {
  readonly code: string;
  readonly name: string;
  readonly unit: string;
  /** Расход на всю позицию, то есть норма расхода × объём. */
  readonly quantity: number;
  /** Цена за единицу, ₽. */
  readonly unitPrice: number;
  readonly total: number;
  readonly source: ResourceLineSource;
  readonly kind: ResourceKind;
  /**
   * Для строк оплаты труда — как получена ставка: точное значение, интерполяция
   * или продолжение шкалы. Для остальных ресурсов null.
   */
  readonly wageOrigin: WageOrigin | null;
}

/**
 * Причина, по которой позиция не посчитана или посчитана с допущением.
 *
 * Перечень закрытый намеренно: расчёт не имеет права придумать новый вид
 * пробела молча — сначала он появляется здесь вместе с объяснением для
 * пользователя. Значения:
 *
 * - «NO_NORM» — норма не найдена в базе;
 * - «BAD_QUANTITY» — объём не число или не положителен;
 * - «BAD_DIVISOR» — в объёме ноль или отрицательный делитель;
 * - «UNIT_MISMATCH» — единица ведомости не совпадает с единицей нормы, а
 *   делителя нет: позиция в расчёт не входит;
 * - «LABOUR_TOTAL_MISMATCH» — итог кода «1» разошёлся с суммой разрядных строк;
 * - «PROJECT_SPECIFIC_RESOURCE» — AbstractResource/ServiceResource без марки;
 * - «QUANTITY_BY_PROJECT» — расход указан как «П», то есть по проекту;
 * - «UNKNOWN_RESOURCE» — код ресурса не попал ни в один известный вид;
 * - «NO_WAGE» — для разряда или должности нет ставки в открытых данных;
 * - «WAGE_EXTRAPOLATED» — разряд выше известного максимума, ставка продолжена;
 * - «NO_PRICE» — в справочниках нет цены на код;
 * - «ZERO_PRICE» — цена в справочнике есть, но равна нулю, то есть не задана;
 * - «NO_CURRENT_PRICE» — нет текущей цены по зоне, расчёт по базе 2022 года;
 * - «NO_OVERHEAD_RATE» — норматив НР или СП не взят по указателю расценки,
 *   начислен резерв документа;
 * - «MACHINIST_HOURS_MISMATCH» — часы машинистов по служебному коду разошлись
 *   с суммой «маш.-ч × звено» по машинам нормы;
 * - «MACHINE_PRICE_INCONSISTENT» — оплата звена больше полной цены маш.-ч,
 *   разложить цену на части нельзя.
 */
export type EstimateGapKind =
  | "NO_NORM"
  | "BAD_QUANTITY"
  | "BAD_DIVISOR"
  | "UNIT_MISMATCH"
  | "LABOUR_TOTAL_MISMATCH"
  | "PROJECT_SPECIFIC_RESOURCE"
  | "QUANTITY_BY_PROJECT"
  | "UNKNOWN_RESOURCE"
  | "NO_WAGE"
  | "WAGE_EXTRAPOLATED"
  | "NO_PRICE"
  | "ZERO_PRICE"
  | "NO_CURRENT_PRICE"
  | "NO_OVERHEAD_RATE"
  | "MACHINIST_HOURS_MISMATCH"
  | "MACHINE_PRICE_INCONSISTENT";

/** Пробел в данных по конкретной позиции. Показывается пользователю, не прячется. */
export interface EstimateGap {
  readonly kind: EstimateGapKind;
  /** Человекочитаемое объяснение одной фразой. */
  readonly message: string;
  /** Код нормы, к которой относится пометка. null, если норма не найдена. */
  readonly code: string | null;
  /**
   * Книга нормы. Без неё пометку нельзя привязать к позиции: один и тот же код
   * в четырёх книгах означает четыре разные работы, и пометка «цена не найдена»
   * для ГЭСНм 01-01-001-01 не закрывает вопрос по ГЭСН 01-01-001-01.
   */
  readonly baseType: string | null;
}

/** Строка сметы: одна норма и один объём работ. */
export interface EstimateLine {
  readonly itemId: string;
  readonly normCode: string;
  /**
   * Книга нормы: «ГЭСН», «ГЭСНм», «ГЭСНр», «ГЭСНп», «ГЭСНмр».
   * Показывается рядом с кодом, потому что один код в четырёх книгах означает
   * четыре разные работы. Смета, в которой напечатано «01-01-001-01» без книги,
   * не проверяема: сметчик не сможет найти в справочнике ту же строку.
   */
  readonly normBaseType: string;
  readonly normName: string;
  readonly normUnit: string;
  /** Объём в единицах нормы. */
  readonly quantity: number;
  /** Объём так, как он записан в ведомости. */
  readonly billQuantity: number;
  readonly billUnit: string;
  readonly sourceQuote: string | null;
  readonly sourceDocument: string | null;
  /**
   * Затраты труда рабочих по разрядным строкам, чел.-ч. Только они оплачены.
   *
   * Труд специалистов сюда не входит: он вынесен в , потому
   * что в книге ГЭСНп такие строки несут 2 565 работ из 2 605, и сумма, где
   * часы инженеров сложены с часами рабочих, а подписана «затраты труда
   * рабочих», называет не ту величину.
   */
  readonly labourHours: number;
  /**
   * Затраты труда специалистов (коды «3-*»: техник, инженер I–III категории,
   * ведущий инженер, главный технолог), чел.-ч.
   *
   * Часы есть, денег нет: ставок ИТР в открытых данных не существует, поэтому
   * каждая такая строка несёт пометку NO_WAGE. Величина печатается отдельно,
   * чтобы было видно, какая часть труда осталась неоплаченной.
   */
  readonly specialistHours: number;
  readonly labourRate: number;
  readonly labourCost: number;
  readonly machinistHours: number;
  readonly machinistSalaryCost: number;
  readonly machineHours: number;
  readonly machineCost: number;
  readonly materialCost: number;
  /** Прямые затраты: оплата труда + машины + материалы. */
  readonly directCost: number;
  /** Фонд оплаты труда: рабочие + машинисты. База для НР и СП. */
  readonly wageFund: number;
  readonly overheadCost: number;
  readonly profitCost: number;
  /**
   * Нормативы, фактически применённые к этой позиции, и их происхождение.
   *
   * Лежат в строке, а не только в параметрах документа, ровно по той же
   * причине, по которой в документе лежит тарифная шкала: норматив теперь
   * свой у каждой расценки, и без напечатанного процента проверить начисление
   * спустя время нельзя — придётся заново поднимать, какой указатель нёс
   * ГЭСН в той редакции базы.
   */
  readonly overheadPercent: number;
  readonly profitPercent: number;
  /** Указатель нормы накладных расходов («Пр/812-001.1»), если он был. */
  readonly overheadRef: string | null;
  /** Указатель нормы сметной прибыли («Пр/774-001.1»), если он был. */
  readonly profitRef: string | null;
  readonly overheadSource: OverheadRateSource;
  readonly profitSource: OverheadRateSource;
  readonly resources: readonly EstimateResourceLine[];
  readonly gaps: readonly EstimateGap[];
}

/** Раздел сметы с подытогами. */
export interface EstimateSection {
  readonly title: string;
  readonly lines: readonly EstimateLine[];
  readonly directCost: number;
  readonly overheadCost: number;
  readonly profitCost: number;
  readonly workCost: number;
}

/** Итоги по документу. */
export interface EstimateTotals {
  readonly directCost: number;
  readonly wageFund: number;
  readonly overheadCost: number;
  readonly profitCost: number;
  readonly workCost: number;
  readonly winterSurcharge: number;
  readonly temporaryStructures: number;
  readonly beforeVat: number;
  readonly vat: number;
  readonly total: number;
}

/** Происхождение данных: что именно легло в основу расчёта. */
export interface EstimateSource {
  readonly title: string;
  readonly url: string;
  readonly edition: string;
}

/** Готовый сметный документ. */
export interface EstimateDocument {
  readonly title: string;
  readonly region: string;
  readonly priceZone: string;
  readonly period: string;
  /** «RESOURCE_INDEX» — ресурсно-индексный метод. */
  readonly method: "RESOURCE_INDEX";
  readonly baseEdition: string;
  readonly parameters: EstimateParameters;
  /**
   * Тарифная шкала, по которой начислена оплата труда. Лежит прямо в документе,
   * чтобы результат можно было проверить спустя время, не восстанавливая,
   * какие именно ставки тогда использовались.
   */
  readonly wageScale: WageScale;
  readonly sections: readonly EstimateSection[];
  readonly totals: EstimateTotals;
  /** Все пробелы по документу: то, что посчитать не удалось или посчитано с допущением. */
  readonly gaps: readonly EstimateGap[];
  readonly sources: readonly EstimateSource[];
  readonly generatedAt: string;
  readonly disclaimer: string;
}
