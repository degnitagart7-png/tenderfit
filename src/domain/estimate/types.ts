/** Цена ресурса с указанием происхождения. */
export interface ResourcePrice {
  readonly code: string;
  readonly name: string;
  readonly unit: string;
  /**
   * Цена за единицу, ₽ без НДС.
   *
   * Для МАШИН смысл зависит от источника, и это нельзя путать (проверено на файлах ФГИС ЦС:
   * `fscsr.xlsx` зоны 266/427, 91.14.02-001 «Автомобили бортовые до 5 т» — цена 800,01,
   * оплата машинистов 912,83, то есть оплата больше цены и внутри неё быть не может):
   * - `BASE_2022` (база ФСБЦ-2022, `prices-base.jsonl`) — ПОЛНАЯ цена маш.-ч, оплата труда
   *   машинистов (`machinistSalary`) в неё входит;
   * - `CURRENT_ZONE` и `BASE_2022_INDEXED` из ФГИС ЦС (ФСЦСР, сплит-форма, «все цены»
   *   зоны) — «Сметная цена, руб./маш.-ч» БЕЗ оплаты труда машинистов: она вынесена в
   *   отдельную колонку и лежит в `machinistSalary`. Полная стоимость маш.-ч — их сумма.
   * Данные зоны хранятся как опубликованы; суммирование делает один раз `resolvePrice`
   * (calculate.ts), а аудит сметы заказчика сравнивает эту цену без оплаты со строкой «ЭМ»
   * заказчика, где оплата идёт отдельными строками «ОТм» (форма 421/пр). Материалов это не касается.
   */
  readonly price: number;
  /**
   * Для машин: оплата труда машинистов, ₽ за один маш.-ч суммарно по составу
   * звена, а не на одного человека. Входит в фонд оплаты труда, а через него —
   * в накладные расходы и сметную прибыль. Для прочих ресурсов null; для машины
   * null — оплата в источнике не указана (сплит-форма, машины вне базы).
   * Входит ли она в `price`, зависит от источника — см. `price`.
   */
  readonly machinistSalary: number | null;
  /** Для машин: численность звена, чел. на маш.-ч. Для прочих — null. */
  readonly machinistHours: number | null;
  readonly source: PriceSourceKind;
  /** Период текущих цен, например «3 квартал 2026 г.». Для базы — null. */
  readonly period: string | null;
  /** Ценовая зона, например «Амурская область (1 зона)». Для базы — null. */
  readonly zone: string | null;
}

/**
 * Опорная точка тарифной шкалы: разряд и ставка за чел.-ч.
 *
 * Берётся из двух открытых источников одной ценовой зоны за один квартал:
 * реестр ставок рабочих (`1-100-*`, покрывает разряды 1,0–3,4) и колонка
 * «Оплата труда машинистов» в текущих ценах ФСЦСР (`4-100-*`, делённая на
 * численность звена — даёт разряды 2–9). Там, где источники пересекаются,
 * значения совпадают до копейки: разряд 2,0 — 598,26 ₽, разряд 3,0 — 653,14 ₽.
 */
export interface WageAnchor {
  /** Средний разряд, например 3.8. */
  readonly rank: number;
  /** Ставка, ₽ за чел.-ч. */
  readonly salary: number;
  /** Откуда взята точка: наименование реестра или выгрузки ФСЦСР. */
  readonly source: string;
}

/** Как получена ставка для разряда. Показывается в расшифровке строки сметы. */
export type WageOrigin =
  /** Точное значение из открытых данных. */
  | "ANCHOR"
  /** Линейная интерполяция между соседними разрядами шкалы. */
  | "INTERPOLATED"
  /** Продолжение шкалы за пределы известных разрядов. Приближение. */
  | "EXTRAPOLATED";

/**
 * Ставка должности специалиста (ИТР) из реестра ставок: «3-200-03» — инженер
 * III категории. У должности нет разряда, поэтому в тарифную сетку она не входит
 * и ищется по коду, как он записан в нормах.
 */
export interface SpecialistWage {
  /** Код, как в нормах и в реестре: «3-100-01», «3-200-03», «3-300-01», «3-400-01». */
  readonly code: string;
  /** Наименование должности из реестра: «Инженер III категории». */
  readonly name: string;
  /** Ставка, ₽ за чел.-ч. */
  readonly salary: number;
  readonly source: string;
}

/** Тарифная шкала ценовой зоны за период. */
export interface WageScale {
  readonly region: string;
  readonly zone: string;
  readonly period: string;
  /** Опорные точки, отсортированные по разряду, без повторов. */
  readonly anchors: readonly WageAnchor[];
  /** Ставка 1-го разряда — знаменатель тарифных коэффициентов. */
  readonly baseSalary: number;
  readonly minRank: number;
  readonly maxRank: number;
  /**
   * Ставки специалистов по кодам («3-*»). Нет у шкал, собранных по первой
   * странице реестра: тогда труд специалистов остаётся без оплаты (NO_WAGE).
   */
  readonly specialists?: readonly SpecialistWage[];
  /**
   * Официальные ставки среднего разряда машинистов («4-100-*») из реестра.
   * Справочные: оплата труда звена в цене машины берётся из выгрузки ФСЦСР
   * зоны, а не отсюда; точки лежат в шкале для проверки и показа.
   */
  readonly machinists?: readonly WageAnchor[];
}

/** Ставка оплаты труда, определённая для конкретного кода ресурса. */
export interface ResolvedWage {
  /** Код ресурса, по которому шла справка, например «1-100-38». */
  readonly code: string;
  readonly rank: number;
  /** Ставка, ₽ за чел.-ч. */
  readonly salary: number;
  readonly origin: WageOrigin;
}

/**
 * Откуда берутся объёмы, от высшего приоритета к низшему.
 *
 * - «CUSTOMER_ESTIMATE», распознанная формой 421/пр, — локальная смета заказчика (ЛСР), которую прочитал
 *   детерминированный разбор (`parseCustomerLsr`, ведомость строит код, без модели). Выше ведомости: ЛСР содержит
 *   все нормы, включая технологические работы (леса, ограждения, транспорт), которых в ведомости нет, и по замеру
 *   даёт 0–5 % отклонения против −40…−95 % у расчёта по ведомости. Ведомость при этом идёт на сверку.
 *   Отдельного значения уровня нет: это тот же «CUSTOMER_ESTIMATE», а «распознана формой 421» — признак группы
 *   позиций (`volumeRank`);
 * - «BILL» — ведомость объёмов работ (ВОР, дефектная ведомость, ведомость в ТЗ
 *   или в приложении к контракту). Если ЛСР формы 421/пр нет, объёмы берутся только из неё;
 * - «CUSTOMER_ESTIMATE», прочитанная моделью, — смета заказчика, не разобранная формой 421/пр (скан, OCR,
 *   нестандартная вёрстка). Ниже ведомости: модель читает такую смету с потерями;
 * - «CONTRACT_ESTIMATE» — смета контракта (приказ 841/пр: «ЛС 02-02-07 Поз.: 3-3.2»).
 *   Это свод ЛСР для оплаты по этапам, а не ведомость: позиции укрупнены, шифров, материалов и
 *   оборудования в них нет. Берётся, только когда нет ни ведомости, ни ЛСР, и расчёт по ней
 *   держится на допущении; при наличии ЛСР служит сверкой;
 * - «SPEC» — ТЗ, спецификация, таблицы проекта. Только когда нет ни ведомости,
 *   ни сметы.
 */
export type VolumeSourceLevel = "BILL" | "CUSTOMER_ESTIMATE" | "CONTRACT_ESTIMATE" | "SPEC";

/** Какой уровень источника лёг в расчёт и из каких документов. */
export interface VolumeSource {
  readonly level: VolumeSourceLevel;
  /** Документы, из которых взяты объёмы расчёта. */
  readonly documents: readonly string[];
  /** Пояснение словами: почему выбран этот уровень. Печатается в карточке и в отчёте. */
  readonly note: string;
  /**
   * Подробности источника по строкам: какие сметы заказчика найдены в нескольких документах и откуда взяты,
   * чья нумерация повторяется, как смета контракта сошлась с ЛСР. Нет поля — добавить нечего.
   */
  readonly details?: readonly string[];
  /**
   * Объёмы взяты из ЛСР формы 421/пр, которую прочитал код (`parseCustomerLsr`), а не модель. Нужен только для показа
   * точности расчёта (`estimateConfidence.ts`). Опциональное: нет поля — признак выводится по документам ЛСР и тексту
   * пояснения; расчёты, посчитанные раньше, его не имеют.
   */
  readonly form421?: boolean;
}

/**
 * Расхождение объёма ведомости со сметой заказчика. Только находка: на сумму
 * расчёта она не влияет, это подсказка человеку, какую из двух цифр проверить.
 */
export interface VolumeFinding {
  /**
   * Что нашла сверка. «VOLUME_DIFF» (по умолчанию, у находок, сохранённых раньше, поля нет) — объёмы одной работы
   * в ведомости и в смете заказчика расходятся. «BILL_ONLY» — работа есть в ведомости, а в смете заказчика
   * (она — основа расчёта) её нет: возможно, заказчик её забыл, и участнику придётся включить её в цену.
   * У «BILL_ONLY» `customerQuantity` — 0, `customerUnit` — пустая строка, `customerDocument` — null.
   */
  readonly kind?: "VOLUME_DIFF" | "BILL_ONLY";
  readonly workName: string;
  readonly billQuantity: number;
  readonly billUnit: string;
  readonly customerQuantity: number;
  readonly customerUnit: string;
  /** Расхождение в процентах от объёма сметы заказчика. */
  readonly diffPercent: number;
  readonly customerDocument: string | null;
  /**
   * Готовая фраза для карточки и отчёта: «В ведомости X, в смете заказчика Y» (расчёт по ведомости),
   * «В смете заказчика X, в ведомости Y — проверьте» (расчёт по смете), «Работа есть в ведомости, но нет в смете заказчика: …».
   */
  readonly message: string;
}

/** Объём в одной из единиц парного значения: «103,65 м3» из «103,65/82,92 м3/т». */
