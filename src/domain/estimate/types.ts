/**
 * Причина, по которой позиция не посчитана или посчитана с допущением.
 *
 * Перечень закрытый намеренно: расчёт не имеет права придумать новый вид
 * пробела молча — сначала он появляется здесь вместе с объяснением для
 * пользователя. Значения:
 *
 * - «NO_NORM» — норма не найдена в базе;
 * - «BAD_QUANTITY» — объём не число или не положителен;
 * - «BAD_DIVISOR» — в объёме ноль или отрицательный делитель;
 * - «UNIT_MISMATCH» — единица ведомости не совпадает с единицей нормы, а
 *   делителя нет: позиция в расчёт не входит;
 * - «LABOUR_TOTAL_MISMATCH» — итог кода «1» разошёлся с суммой разрядных строк;
 * - «PROJECT_SPECIFIC_RESOURCE» — AbstractResource/ServiceResource без марки;
 * - «QUANTITY_BY_PROJECT» — расход указан как «П», то есть по проекту;
 * - «UNKNOWN_RESOURCE» — код ресурса не попал ни в один известный вид;
 * - «NO_WAGE» — для разряда или должности нет ставки в открытых данных;
 * - «WAGE_EXTRAPOLATED» — разряд выше известного максимума, ставка продолжена;
 * - «NO_PRICE» — в справочниках нет цены на код;
 * - «ZERO_PRICE» — цена в справочнике есть, но равна нулю, то есть не задана;
 * - «NO_CURRENT_PRICE» — нет текущей цены по зоне, расчёт по базе 2022 года;
 * - «NO_OVERHEAD_RATE» — норматив НР или СП не взят по указателю расценки,
 *   начислен резерв документа;
 * - «MACHINIST_HOURS_MISMATCH» — часы машинистов по служебному коду разошлись
 *   с суммой «маш.-ч × звено» по машинам нормы;
 * - «MACHINE_PRICE_INCONSISTENT» — оплата звена больше полной цены маш.-ч,
 *   разложить цену на части нельзя;
 * - «MACHINIST_PAY_UNKNOWN» — цена машины из ФГИС ЦС (сплит-форма) приходит без оплаты труда
 *   машинистов, а взять оплату звена из базы 2022 нечем (машины нет в базе или не задан индекс
 *   труда машинистов): ОТм не включена в стоимость маш.-ч и в ФОТ, прямые затраты и начисления НР и СП
 *   по этой машине занижены;
 * - «CUSTOMER_PRICE» — нашей нормы или цены нет, позиция вошла в итог по цене
 *   заказчика из его сметы. Не выбывание, а допущение: деньги в итоге есть, но не
 *   проверены нашими ценами;
 * - «INDEXED_PRICE» — в книге цен зоны ресурса нет, цена взята из «всех цен сплит-
 *   формы» и получена индексом к группе однородных ресурсов. Пометка, не допущение
 *   уровня «база 2022»: уровень цен текущий;
 * - «AI_MATERIAL_PICK» — материал нормы «по проекту» (ресурс без марки с числовым расходом) подобран ИИ в справочнике цен и вошёл в строку.
 *   Информационная пометка, как «INDEXED_PRICE»: не выбывание и не пробел, но материал выбран не документом — проверьте;
 * - «NORMATIVE_NOT_APPLIED» — норматив (зимнее удорожание, временные здания) не начислен:
 *   неизвестны вид работ, сроки или часть территории, либо норматива в процентах для такого
 *   вида работ нет. Сумма в итоге занижена на этот норматив, причина названа в сообщении.
 * - «BIM_NO_INDEX» — базисно-индексный метод: индекс письма Минстроя для субъекта, объекта и квартала
 *   найден не полностью или объект строительства определён не однозначно; сказано, какие индексы применены;
 * - «BIM_TER_AS_FER» — базисно-индексный метод: заказчик считает по ТЕР региона, а открытой базы ТЕР нет —
 *   посчитано по ФЕР с индексами к ФЕР, возможна разница;
 * - «BIM_FALLBACK_RIM» — смета заказчика на ФЕР/ТЕР, но ФЕР-2020 на сервере не собраны: посчитано
 *   ресурсно-индексным методом;
 * - «PRICE_LEVEL_DIFFERS» — смета заказчика составлена в другой ценовой зоне или в другом квартале, чем наш расчёт:
 *   цены ресурсов различаются, построчное сравнение цен со сметой заказчика неточно. Не отказ: расчёт идёт в нашем уровне.
 * - «CUSTOMER_BASE_DIFFERS» — смета заказчика составлена по другой базе норм (ТСН-2001 Москвы), а наша — ФСНБ-2022: построчное сравнение норм
 *   не «like-for-like». Одна пометка на документ; позиции такой сметы идут через подбор нормы по наименованию с пометкой «проверьте» или по цене заказчика.
 * - «BILL_CHUNK_UNREAD» — фрагмент документа не прочитан моделью (сбой шлюза или прода, ответ не в формате) даже со второй попытки: строки ведомости из
 *   него потеряны, а смета по остальным документам посчитана. Сумма может быть занижена; одна пометка на фрагмент с его номером и причиной.
 * - «NO_VOLUME_SOURCE» — в документах закупки нет ни ведомости объёмов, ни сметы заказчика, ни сметы контракта, ни таблицы с количествами: смета пуста.
 *   Текст называет, что просмотрено, и что делать (загрузить ВОР или смету заказчика на странице «Смета»; `.gsfx` и `.xml` сметных программ не читаются). Один на документ.
 */
export type EstimateGapKind =
  | "NO_NORM"
  | "BAD_QUANTITY"
  | "BAD_DIVISOR"
  | "UNIT_MISMATCH"
  | "LABOUR_TOTAL_MISMATCH"
  | "PROJECT_SPECIFIC_RESOURCE"
  | "QUANTITY_BY_PROJECT"
  | "UNKNOWN_RESOURCE"
  | "NO_WAGE"
  | "WAGE_EXTRAPOLATED"
  | "NO_PRICE"
  | "ZERO_PRICE"
  | "NO_CURRENT_PRICE"
  | "NO_OVERHEAD_RATE"
  | "MACHINIST_HOURS_MISMATCH"
  | "MACHINE_PRICE_INCONSISTENT"
  | "MACHINIST_PAY_UNKNOWN"
  | "CUSTOMER_PRICE"
  | "INDEXED_PRICE"
  | "AI_MATERIAL_PICK"
  | "NORMATIVE_NOT_APPLIED"
  | "BIM_NO_INDEX"
  | "BIM_TER_AS_FER"
  | "BIM_FALLBACK_RIM"
