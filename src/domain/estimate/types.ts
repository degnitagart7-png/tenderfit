/**
 * Типы сметного расчёта по открытым данным ФГИС ЦС.
 *
 * Источник фактов — выгрузка ФСНБ-2022 (приказ Минстроя России от 12.08.2026
 * № 527/пр): нормы ГЭСН, Федеральная сметная база цен (ФСБЦ) в уровне
 * 01.01.2022, текущие сметные цены строительных ресурсов (ФСЦСР) по ценовым
 * зонам и кварталам, реестр ставок оплаты труда рабочих по разрядам.
 *
 * Разбор того, что реально отдаёт портал и где проходят границы автоматизации,
 * — в docs/REFERENCE_GRAND_SMETA.md.
 */

/**
 * Вид ресурса в норме. Определяется по коду, а не по наименованию.
 *
 * В выгрузке ИАС ЦС сосуществуют две записи труда рабочих, и они никогда не
 * встречаются в одной норме (проверено на всех 30 028 нормах «ГЭСН.xml»:
 * 23 310 норм с «1-100-*», 3 273 с «2-100-*», ни одной с обеими). Поэтому
 * деньги начисляются только по разрядным строкам, а итоговая строка «1»
 * служит справочной сверкой.
 */
export type ResourceKind =
  /**
   * Затраты труда рабочих, чел.-ч, с указанием разряда. Оцениваются по шкале
   * оплаты труда. Коды «1-100-38» (средний разряд 3,8) и «2-100-04»
   * (рабочий 4 разряда).
   */
  | "LABOUR"
  /**
   * Итоговые затраты труда рабочих, чел.-ч. Служебный код «1»; равен сумме
   * строк «2-100-*» той же нормы. В расчёте не оценивается — иначе труд
   * был бы посчитан дважды.
   */
  | "WORKER_HOURS_TOTAL"
  /**
   * Затраты труда машинистов, чел.-ч. Служебный код «2» и код звена машины
   * «4-100-060». Оплата уже внутри стоимости маш.-ч, отдельно не оценивается.
   */
  | "MACHINIST_HOURS"
  /** Машина или механизм. Код начинается с «91.». */
  | "MACHINE"
  /** Материал, изделие, конструкция или оборудование. */
  | "MATERIAL"
  /** Код не распознан. Позиция попадает в список пробелов, а не в расчёт. */
  | "UNKNOWN";

/** Один ресурс в составе нормы. */
export interface NormResource {
  readonly code: string;
  readonly kind: ResourceKind;
  /** Наименование из нормы или из классификатора; может быть пустым. */
  readonly name: string;
  readonly quantity: number;
  /** Единица измерения ресурса: «чел.-ч», «маш.-ч», «м3», «т» и т. п. */
  readonly unit: string;
  /**
   * Пометка количества, когда в выгрузке оно не число. «П» означает «по
   * проекту»: расход определяется проектной документацией, а не нормой. В
   * «ГЭСН.xml» таких 15 437, и при них quantity равен нулю.
   */
  readonly quantityNote: string | null;
  /**
   * Ресурс без конкретной марки. В выгрузке это AbstractResource (код группы,
   * например «01.7.12.16», с атрибутом TechnologyGroups) и ServiceResource
   * («999-9901», «МАТЕРИАЛЫ (см. приложение)»). Цены на такой код в
   * классификаторе нет: стоимость выбирается проектом, поэтому позиция идёт в
   * пробелы, а не в расчёт.
   */
  readonly projectSpecific: boolean;
  /** Код технологической группы из атрибута TechnologyGroups, если он есть. */
  readonly technologyGroup: string | null;
}

/** Норма ГЭСН — строка расценки, к которой привязывается объём работ. */
export interface NormRecord {
  /**
   * Полный код, например «01-01-001-01».
   *
   * Уникален только вместе с `baseType`: в выгрузке ФГИС ЦС 2 784 кода
   * встречаются больше чем в одной книге, и «01-01-001-01» — это и драглайн,
   * и токарный станок, и синхронный генератор, и замок двери шахты лифта.
   */
  readonly code: string;
  /** Код таблицы, например «01-01-001». */
  readonly tableCode: string;
  /** Наименование таблицы + окончание строки: то, что видит сметчик. */
  readonly fullName: string;
  /** Окончание строки из атрибута EndName. */
  readonly endName: string;
  /** Единица измерения нормы, например «1000 м3». */
  readonly unit: string;
  /** Код сборника, например «01». */
  readonly collectionCode: string;
  /** Наименование сборника, например «Земляные работы». */
  readonly collectionName: string;
  /** Раздел внутри сборника. */
  readonly sectionName: string;
  /** Подраздел внутри раздела. */
  readonly subsectionName: string;
  /** Тип базы: «ГЭСН», «ГЭСНм», «ГЭСНр», «ГЭСНп», «ГЭСНмр». */
  readonly baseType: string;
  /** Состав работ из блока Content — то, чем норма обосновывается. */
  readonly content: readonly string[];
  readonly resources: readonly NormResource[];
  /** Указатель на норму накладных расходов из атрибута Nr («Пр/812-001.1»). */
  readonly overheadRef: string | null;
  /** Указатель на норму сметной прибыли из атрибута Sp («Пр/774-001.1»). */
  readonly profitRef: string | null;
}

