import { describe, expect, it } from "vitest";

import { checkMaterialFamily, keyMaterialWords, materialFamiliesOf, wordsRelated } from "@/domain/estimate/normMaterialFamily";

const BITUMEN_WORK = "Устройство кровель из листов волнистых битумных";

describe("ключевые слова названия", () => {
  it("общие слова, названия работ, размеры и марки ключевыми не бывают", () => {
    expect(keyMaterialWords("Устройство кровель из листов волнистых битумных")).toEqual(["волнистых", "битумных"]);
    expect(keyMaterialWords("Профилированный лист оцинкованный С8-1150-0,5")).toEqual(["профилированный", "оцинкованный"]);
    expect(keyMaterialWords("Материалы кровельные")).toEqual([]);
    expect(keyMaterialWords("")).toEqual([]);
  });

  it("слова родственны по началу: окончания не мешают, разные корни — не родственны", () => {
    expect(wordsRelated("битумные", "битумный")).toBe(true);
    expect(wordsRelated("смол", "смолы")).toBe(true);
    expect(wordsRelated("волнистых", "волнистый")).toBe(true);
    expect(wordsRelated("профнастил", "профилированный")).toBe(false);
    expect(wordsRelated("битумные", "оцинкованный")).toBe(false);
    expect(wordsRelated("кирпич", "кирпичный")).toBe(true);
  });
});

describe("род материала", () => {
  it("битумные и металл, полимеры и прочие определяются по корню", () => {
    expect([...materialFamiliesOf("Лист волнистый ондулин")]).toEqual(["BITUMEN"]);
    expect([...materialFamiliesOf("Профнастил С21")]).toEqual(["METAL"]);
    expect([...materialFamiliesOf("Профилированный лист оцинкованный")]).toEqual(["METAL"]);
    expect([...materialFamiliesOf("Состав на основе полиуретановых смол")]).toEqual(["POLYMER"]);
    expect([...materialFamiliesOf("Листы асбестоцементные волнистые")]).toEqual(["CONCRETE"]);
    expect([...materialFamiliesOf("Битумно-полимерный наплавляемый материал")].sort()).toEqual(["BITUMEN", "POLYMER"]);
    expect([...materialFamiliesOf("Болты строительные")]).toEqual([]);
  });
});

describe("проверка соответствия материала ресурсу нормы и работе", () => {
  const check = (materialName: string, resourceName: string, workName: string) => checkMaterialFamily({ materialName, resourceName, workName });

  it("случай кровли: стальной профилированный лист вместо битумного отклоняется", () => {
    const verdict = check("Профилированный лист оцинкованный НС35-1000-0,7", "Листы волнистые битумные", BITUMEN_WORK);
    expect(verdict.ok).toBe(false);
    expect(verdict).toMatchObject({ reason: expect.stringContaining("другого рода") });
  });

  it("обратный обмен: битумный лист вместо профилированного отклоняется", () => {
    expect(check("Лист волнистый битумный ондулин", "Профилированный лист", "Монтаж кровли из профилированного листа").ok).toBe(false);
    expect(check("Листы волнистые битумные кровельные", "Профилированный лист", "Монтаж кровли из профилированного листа").ok).toBe(false);
  });

  it("свой материал принимается: битумный — битумному, стальной — стальному, ондулин — битумному", () => {
    expect(check("Листы волнистые битумные кровельные толщиной 3 мм", "Листы волнистые битумные", BITUMEN_WORK).ok).toBe(true);
    expect(check("Лист волнистый ондулин Смарт", "Листы волнистые битумные", BITUMEN_WORK).ok).toBe(true);
    expect(check("Профнастил оцинкованный С21", "Профилированный лист", "Монтаж кровли из профилированного листа").ok).toBe(true);
  });

  it("асбестоцементный волнистый лист вместо битумного отклоняется: общий корень «волнист» не спасает", () => {
    expect(check("Листы асбестоцементные волнистые", "Листы волнистые битумные", BITUMEN_WORK).ok).toBe(false);
  });

  it("название ресурса не называет род — решает работа; ничего не названо — принимается", () => {
    expect(check("Профилированный лист оцинкованный", "Материалы кровельные", BITUMEN_WORK).ok).toBe(false);
    expect(check("Лист волнистый битумный", "Материалы кровельные", BITUMEN_WORK).ok).toBe(true);
    expect(check("Лист кровельный", "Материалы кровельные", "Устройство кровель").ok).toBe(true);
  });

  it("род не назван ни у материала, ни у нужды, но ключевые слова разные — отклоняется; общее слово — принимается", () => {
    const rejected = check("Мастика герметизирующая тиоколовая", "Ленты уплотнительные", "Герметизация швов");
    expect(rejected.ok).toBe(false);
    expect(rejected).toMatchObject({ reason: expect.stringContaining("ключевого слова") });
    expect(check("Ленты уплотнительные самоклеящиеся", "Ленты уплотнительные", "Герметизация швов").ok).toBe(true);
  });

  it("у нужды нет ключевых слов — сказать нечего, принимается", () => {
    expect(check("Мастика герметизирующая", "Материалы", "Устройство").ok).toBe(true);
  });

  it("материал из двух родов принимается, если один из них совпал с нуждой", () => {
    expect(check("Профнастил с полимерным покрытием", "Профилированный лист", "Монтаж кровли из профилированного листа").ok).toBe(true);
    expect(check("Лист стальной с полимерным покрытием", "Листы волнистые битумные", BITUMEN_WORK).ok).toBe(false);
  });

  it("состав на основе полиуретановых смол: эпоксидный состав того же рода не режется — выбор между ними за моделью", () => {
    expect(check("Состав двухкомпонентный на основе эпоксидных смол", "Состав двухкомпонентный на основе полиуретановых смол", "Изоляция кровли напыляемым пенополиуретаном").ok).toBe(true);
    expect(check("Болты стальные строительные с гайками", "Состав двухкомпонентный на основе полиуретановых смол", "Изоляция кровли напыляемым пенополиуретаном").ok).toBe(false);
  });
});
