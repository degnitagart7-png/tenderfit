/** Слова названия для сопоставления: без регистра и «ё», «г.» → «город», без пунктуации и цифр сносок. */
export function subjectWords(raw: string): string[] {
  return raw
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/(?<![а-я])г\./g, "город ")
    .replace(/\(\s*\d+\s*зона\s*\)/g, " ")
    .replace(/[^а-я\s-]/g, " ")
    .split(/[\s-]+/)
    .filter((word) => word !== "");
}

const BY_WORDS: ReadonlyArray<{ readonly subject: string; readonly words: ReadonlySet<string> }> = BIM_SUBJECTS.map((subject) => ({
  subject,
  words: new Set(subjectWords(subject)),
}));

/** Номер зоны из «(2 зона)»; нет — null. */
export function zoneOfName(raw: string): number | null {
  const match = /\(\s*(\d+)\s*зона\s*\)/i.exec(raw);
  return match?.[1] === undefined ? null : Number.parseInt(match[1], 10);
}

/** Субъект справочника по названию из письма или зоны; нет однозначного — null. */
export function resolveSubject(raw: string): string | null {
  const words = [...new Set(subjectWords(raw))];
  if (words.length === 0) return null;
  const fits = BY_WORDS.filter((entry) => words.every((word) => entry.words.has(word)));
  if (fits.length === 0) return null;
  const tightest = Math.min(...fits.map((entry) => entry.words.size));
  const best = fits.filter((entry) => entry.words.size === tightest);
  // Одно слово («Республика», «область») подходит многим: это не название субъекта.
  return best.length === 1 ? (best[0] as { subject: string }).subject : null;
}

/** Субъект по названию ценовой зоны: «Иркутская область (1 зона)» → «Иркутская область». */
export function subjectOfZoneName(zoneName: string): string | null {
  return resolveSubject(zoneName);
}
