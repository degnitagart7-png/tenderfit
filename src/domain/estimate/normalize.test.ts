import { describe, expect, it } from "vitest";
import {
  discriminativeWord,
  normalizeNormCode,
  normalizeText,
  stem,
  tableCodeOf,
  tokenizeForMatch,
  uniqueTokens,
} from "@/domain/estimate/normalize";

/**
 * Нормализация наименований и кодов.
 *
 * Модуль кажется вспомогательным, но через него проходит и подбор нормы, и
 * поиск по явному коду. Ошибка здесь не падает: она превращается в пустую
 * выдачу или в подобранную не ту расценку. Поэтому проверяются конкретные
 * формы записи, которые встречаются в документации закупок и в выгрузке
 * ФСНБ-2022, а не абстрактные строки.
 */
describe("normalizeText", () => {
  it("приводит регистр, убирает кавычки и «ёлочки»", () => {
    expect(normalizeText('Разработка грунта «драглайн» 15 м3')).toBe(
      "разработка грунта драглайн 15 м3",
    );
  });

  it("заменяет «ё» на «е»: в выгрузке обе формы встречаются вперемешку", () => {
    expect(normalizeText("Разработка мёрзлого грунта")).toBe("разработка мерзлого грунта");
  });

  it("схлопывает пробелы и переводы строк", () => {
    expect(normalizeText("  Монтаж   \nконструкций  ")).toBe("монтаж конструкций");
  });

  it("пустая строка остаётся пустой", () => {
    expect(normalizeText("   ")).toBe("");
  });
});

describe("tokenizeForMatch", () => {
  it("сохраняет единицу измерения одним токеном: «м3» и «м2» — разные нормы", () => {
    expect(tokenizeForMatch("Устройство стяжки 15 м3")).toEqual(["устройство", "стяжки", "15", "м3"]);
    expect(tokenizeForMatch("Устройство стяжки 15 м2")).toEqual(["устройство", "стяжки", "15", "м2"]);
  });

  it("сохраняет диапазоны и десятичные дроби, которыми различаются соседние строки", () => {
    // Наименование таблицы 01-01-001 из «ГЭСН.xml»: «...с ковшом вместимостью
    // 15; 10; 6,3-6,5 м3». Потеря запятой склеила бы три разные строки.
    expect(tokenizeForMatch("ковшом вместимостью 6,3-6,5 м3")).toEqual([
      "ковшом",
      "вместимостью",
      "6,3",
      "6,5",
      "м3",
    ]);
  });

  it("отбрасывает служебные слова", () => {
    expect(tokenizeForMatch("Разработка грунта в отвал для строительства")).toEqual([
      "разработка",
      "грунта",
      "отвал",
      "строительства",
    ]);
  });

  it("знаки препинания не становятся токенами", () => {
    expect(tokenizeForMatch("из керамических труб диаметром: 100 мм,")).toEqual([
      "керамических",
      "труб",
      "диаметром",
      "100",
      "мм",
    ]);
  });

  it("строка без слов и цифр не даёт токенов", () => {
    expect(tokenizeForMatch("--- ... ///")).toEqual([]);
  });
});

describe("uniqueTokens", () => {
  it("убирает повторы, сохраняя порядок первого вхождения", () => {
    expect(uniqueTokens("грунт глина грунт песок глина")).toEqual(["грунт", "глина", "песок"]);
  });

  it("повтор через другую форму слова остаётся: уникальность по токену, не по основе", () => {
    // Основы «бетонный» и «бетонные» совпадут уже в подборщике норм, а здесь
    // это два разных токена — и это намеренно: uniqueTokens не знает про stem.
    expect(uniqueTokens("бетонный бетонные")).toEqual(["бетонный", "бетонные"]);
  });

  it("пустой вход даёт пустой список", () => {
    expect(uniqueTokens("")).toEqual([]);
  });
});

describe("normalizeNormCode", () => {
  it("канонический код возвращается без изменений", () => {
    expect(normalizeNormCode("01-01-001-01")).toBe("01-01-001-01");
    expect(normalizeNormCode("  01-01-001-01  ")).toBe("01-01-001-01");
  });

  it("убирает название книги и регистр не важен", () => {
    expect(normalizeNormCode("ГЭСН 01-01-001-01")).toBe("01-01-001-01");
    expect(normalizeNormCode("гэсн 01-01-001-01")).toBe("01-01-001-01");
    expect(normalizeNormCode("ФЕР 10-01-001-01")).toBe("10-01-001-01");
    expect(normalizeNormCode("ТЕР 10-01-001-01")).toBe("10-01-001-01");
  });

  it("убирает книгу вместе с суффиксом: «ГЭСНм», «ГЭСНр», «ГЭСНп», «ГЭСНмр»", () => {
    // Сметчики пишут код вместе с книгой. Если отбросить только «ГЭСН», от кода
    // останется «М08-01-001-01» — он не находится ни в одной книге, и позиция
    // исчезает из сметы без объяснения.
    expect(normalizeNormCode("ГЭСНм 08-01-001-01")).toBe("08-01-001-01");
    expect(normalizeNormCode("ГЭСНр 61-01-001-01")).toBe("61-01-001-01");
    expect(normalizeNormCode("ГЭСНп 01-01-001-01")).toBe("01-01-001-01");
    expect(normalizeNormCode("ГЭСНмр 01-01-001-01")).toBe("01-01-001-01");
    expect(normalizeNormCode("ФЕРмр 01-01-001-01")).toBe("01-01-001-01");
  });

  it("принимает дефис вместо пробела между книгой и кодом", () => {
    expect(normalizeNormCode("ГЭСН-01-01-001-01")).toBe("01-01-001-01");
    expect(normalizeNormCode("ГЭСНм-08-01-001-01")).toBe("08-01-001-01");
  });

  it("не трогает код, который начинается с цифр", () => {
    expect(normalizeNormCode("41-01-002-03")).toBe("41-01-002-03");
  });
});

describe("tableCodeOf", () => {
  it("отрезает номер строки от кода нормы", () => {
    expect(tableCodeOf("01-01-001-01")).toBe("01-01-001");
    expect(tableCodeOf("ГЭСНм 08-01-001-12")).toBe("08-01-001");
  });

  it("код таблицы возвращается как есть", () => {
    expect(tableCodeOf("01-01-001")).toBe("01-01-001");
  });

  it("короткий код не добивается дефисами", () => {
    expect(tableCodeOf("01-01")).toBe("01-01");
    expect(tableCodeOf("")).toBe("");
  });
});

describe("stem", () => {
  it("склейка окончаний: «бетонный» и «бетонные» дают одну основу", () => {
    expect(stem("бетонный")).toBe(stem("бетонные"));
    expect(stem("бетонный")).toBe("бетонн");
  });

  it("короткие слова не трогаются: «монтаж» не должен совпасть с «монтажник»", () => {
    expect(stem("монтаж")).toBe("монтаж");
    expect(stem("монтажник")).toBe("монтажн");
    expect(stem("монтаж")).not.toBe(stem("монтажник"));
  });

  it("токены с цифрами и пустая строка возвращаются без изменений", () => {
    expect(stem("м3")).toBe("м3");
    expect(stem("15")).toBe("15");
    expect(stem("6,3")).toBe("6,3");
    expect(stem("")).toBe("");
  });

  it("не идемпотентен — поэтому основы различающих слов вычисляются один раз", () => {
    // Если применить stem дважды, «установка» доедет до «устан» и перестанет
    // совпадать с основой, которую построил подборщик. Словарь различающих слов
    // приводится к основам ровно одним вызовом, и этот тест фиксирует причину.
    expect(stem("установка")).toBe("установ");
    expect(stem(stem("установка"))).toBe("устан");
    expect(discriminativeWord(stem("установка"))).toBe("установка");
    expect(discriminativeWord(stem(stem("установка")))).toBeNull();
  });
});

/**
 * Словарь различающих слов повторяется в тесте намеренно.
 *
 * Проверка состоит не в том, что конкретное слово есть в словаре, а в том, что
 * все слова словаря различимы после приведения к основе. Если два слова дадут
 * одну основу, карта «основа → слово» молча оставит одно из них, и именно это
 * уже случалось: бонус сравнивал основу со словарной формой и не срабатывал
 * почти никогда.
 */
const DISCRIMINATIVE = [
  "разработка",
  "разборка",
  "монтаж",
  "демонтаж",
  "установка",
  "укладка",
  "заливка",
  "бетонирование",
  "окраска",
  "штукатурка",
  "кладка",
  "сварка",
  "гидроизоляция",
  "теплоизоляция",
  "устройство",
  "засыпка",
  "уплотнение",
  "перевозка",
  "погрузка",
] as const;

describe("discriminativeWord", () => {
  it("словарная форма возвращается сама собой", () => {
    for (const word of DISCRIMINATIVE) {
      expect(discriminativeWord(word), word).toBe(word);
    }
  });

  it("основа словарной формы возвращается словарной формой", () => {
    // То, с чем реально сравнивается токен в подборщике норм.
    for (const word of DISCRIMINATIVE) {
      expect(discriminativeWord(stem(word)), `основа ${stem(word)}`).toBe(word);
    }
  });

  it("основы всех слов словаря различны", () => {
    const stems = DISCRIMINATIVE.map((word) => stem(word));
    expect(new Set(stems).size).toBe(DISCRIMINATIVE.length);
  });

  it("различает «разработку» и «разборку» — пара, ради которой бонус вводился", () => {
    expect(discriminativeWord(stem("разработка"))).toBe("разработка");
    expect(discriminativeWord(stem("разборка"))).toBe("разборка");
    expect(stem("разработка")).not.toBe(stem("разборка"));
  });

  it("короткие слова словаря не меняются при приведении к основе", () => {
    for (const word of ["монтаж", "кладка", "сварка"]) {
      expect(stem(word)).toBe(word);
      expect(discriminativeWord(word)).toBe(word);
    }
  });

  it("обычное слово сметного текста не считается различающим", () => {
    expect(discriminativeWord("грунт")).toBeNull();
    expect(discriminativeWord("грунта")).toBeNull();
    expect(discriminativeWord("бетон")).toBeNull();
    expect(discriminativeWord("экскаватор")).toBeNull();
    expect(discriminativeWord("м3")).toBeNull();
    expect(discriminativeWord("15")).toBeNull();
    expect(discriminativeWord("")).toBeNull();
  });

  it("обрубок основы не принимается за словарную форму", () => {
    // «устан» — это основа от основы «установ». Подборщик её не построит, но
    // если построит, отвечать нужно null, а не выдуманным словом.
    expect(discriminativeWord("устан")).toBeNull();
    expect(discriminativeWord("гидроизол")).toBeNull();
    expect(discriminativeWord("разработк")).toBeNull();
  });
});
