/**
 * Нормализация наименований для сопоставления работы из ведомости объёмов
 * работ с нормой ГЭСН.
 *
 * Наименования в ФСНБ-2022 написаны канцеляритом с кавычками, запятыми и «ёлочками»:
 * «Разработка грунта в отвал экскаваторами &quot;драглайн&quot; одноковшовыми
 * электрическими шагающими ... с ковшом вместимостью 15; 10; 6,3-6,5 м3».
 * Документация закупки пишет то же самое другими словами и с опечатками.
 * Сопоставление поэтому идёт по основам слов, а не посимвольно — тот же
 * принцип, что уже применён в полнотекстовом поиске по закупкам.
 *
 * Модуль чистый: только строки на входе и строки на выходе.
 */

/**
 * Служебные слова, которые встречаются почти в каждой норме и потому не несут
 * различающей силы. Их исключаем из токенов сопоставления, но не из отображения.
 */
const STOP_WORDS: ReadonlySet<string> = new Set([
  "и",
  "в",
  "во",
  "на",
  "с",
  "со",
  "по",
  "из",
  "до",
  "от",
  "не",
  "для",
  "при",
  "работ",
  "работа",
  "работы",
  "выполнение",
  "сборник",
  "таблица",
  "норма",
  "расценка",
]);

/**
 * Слова, которые в сметной лексике различают нормы сильнее прочих. Дают
 * небольшой бонус при ранжировании — иначе «разработка грунта» и «разборка
 * грунта» набирают одинаково.
 */
const DISCRIMINATIVE_WORDS: ReadonlySet<string> = new Set([
  "разработка",
  "разборка",
  "монтаж",
  "демонтаж",
  "установка",
  "укладка",
  "заливка",
  "бетонирование",
  "окраска",
  "штукатурка",
  "кладка",
  "сварка",
  "гидроизоляция",
  "теплоизоляция",
  "устройство",
  "засыпка",
  "уплотнение",
  "перевозка",
  "погрузка",
]);

/** Приводит текст к форме сопоставления: нижний регистр, «е» вместо «ё», без знаков. */
export function normalizeText(input: string): string {
  return input
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/"/g, "")
    .replace(/«|»/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * Разбивает на токены сопоставления.
 *
 * Числа с запятой и диапазоны («6,3-6,5», «до 5 м2») важны: именно они
 * отличают соседние строки одной таблицы. Поэтому цифры сохраняем целиком,
 * а разделители считаем границами только между буквенными словами.
 *
 * Единицы измерения тоже сохраняем целиком: «м3» и «м2» — это разные нормы,
 * а не один токен «м» плюс число, которое совпадёт с чем угодно.
 */
export function tokenizeForMatch(input: string): string[] {
  const normalized = normalizeText(input);
  const raw = normalized.match(/[0-9]+(?:[.,][0-9]+)*|[a-zа-я]+[0-9]*/g) ?? [];
  const tokens: string[] = [];
  for (const token of raw) {
    const cleaned = token.replace(/[.,]+$/g, "");
    if (cleaned.length === 0) continue;
    if (STOP_WORDS.has(cleaned)) continue;
    tokens.push(cleaned);
  }
  return tokens;
}

/** Уникальные токены без потери порядка. */
export function uniqueTokens(input: string): string[] {
  const seen = new Set<string>();
  const result: string[] = [];
  for (const token of tokenizeForMatch(input)) {
    if (seen.has(token)) continue;
    seen.add(token);
    result.push(token);
  }
  return result;
}

/**
 * Префикс книги в коде: «ГЭСН», «ГЭСНм», «ГЭСНр», «ГЭСНп», «ГЭСНмр» и то же для
 * ФЕР и ТЕР, с необязательным пробелом или дефисом перед цифрами.
 *
 * Суффикс книги обязателен к учёту: сметчики пишут «ГЭСНм 08-01-001-01», и если
 * отбросить только «ГЭСН», от кода останется «М08-01-001-01». Такой код не
 * находится ни в одной книге, подбор молча возвращает пустой список, и позиция
 * пропадает из сметы без объяснения.
 */
const BOOK_PREFIX = /^(?:ГЭСН|ФЕР|ТЕР)(?:МР|[МРП])?\s*-?\s*/i;

/** Код нормы к каноническому виду: «01-01-001-01», пробелы и книга убираем. */
export function normalizeNormCode(input: string): string {
  const trimmed = input.trim().toUpperCase();
  const withoutPrefix = trimmed.replace(BOOK_PREFIX, "");
  return withoutPrefix.replace(/\s+/g, "");
}

/** Код таблицы из полного кода нормы: «01-01-001-01» → «01-01-001». */
export function tableCodeOf(normCode: string): string {
  const canonical = normalizeNormCode(normCode);
  const parts = canonical.split("-");
  if (parts.length <= 3) return canonical;
  return parts.slice(0, 3).join("-");
}

/**
 * Основы различающих слов: словарная форма → то, с чем реально сравниваются
 * токены подбора.
 *
 * Подборщик норм приводит и запрос, и наименование нормы к основам, поэтому
 * сравнивать основу со словарной формой бесполезно: «разборка» после
 * отбрасывания двух последних букв превращается в «разбор». Из девятнадцати
 * слов словаря без основы совпадают только «монтаж», «кладка» и «сварка» —
 * короче семи букв, — и ровно та пара, ради которой бонус вводился
 * («разработка грунта» против «разборка грунта»), не срабатывала бы никогда.
 */
const DISCRIMINATIVE_STEMS: ReadonlyMap<string, string> = new Map(
  [...DISCRIMINATIVE_WORDS].map((word) => [stem(word), word]),
);

/**
 * Словарная форма различающего слова по токену или его основе: «разбор» →
 * «разборка». Показывать пользователю обрубок основы нельзя — объяснение
 * подборки читает сметчик, и «совпал вид работ: разбор» он прочитает как
 * опечатку в программе.
 */
export function discriminativeWord(token: string): string | null {
  if (DISCRIMINATIVE_WORDS.has(token)) return token;
  return DISCRIMINATIVE_STEMS.get(token) ?? null;
}

/**
 * Основа слова: у слов длиннее шести букв отбрасываются две последние.
 * Грубый стемминг без словаря — достаточный, чтобы «бетонные» и «бетонный»
 * совпали, и при этом не склеивающий «монтаж» с «монтажник»: короткие слова
 * не трогаются вовсе.
 */
export function stem(token: string): string {
  if (!/^[a-zа-я]+$/.test(token)) return token;
  if (token.length <= 6) return token;
  return token.slice(0, token.length - 2);
}
