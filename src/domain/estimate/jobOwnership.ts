/**
 * Чей расчёт сметы: правила доступа к заданиям `estimate`.
 *
 * Расчёт принадлежит тому, кто его поставил: в `sync_jobs.requested_by` лежит почта вошедшего
 * (`requestEmail`), а у служебного запроса — метка «ui». До 20.10.2026 ручки `/api/estimate*`
 * владельца не проверяли: `GET ?jobId=` отдавал любое задание по номеру (вместе с результатом по
 * загруженным файлам), а `GET ?tenderId=` — последнюю смету закупки от кого угодно, поэтому смета,
 * посчитанная одним человеком, открывалась у всех на карточке закупки. Правило одно на все ручки,
 * чтобы оно не расходилось между ними.
 *
 * Кто есть кто:
 *  - вошедший (`email` задан) видит и повторно использует только свои задания;
 *  - администратор (почта в ADMIN_EMAILS) может открыть любое задание по номеру — по ссылке из
 *    письма о сбое, — но списки и «последняя смета закупки» у него тоже только свои;
 *  - служебный запрос (воркер, ключ владельца, режим разработки без входа: почты нет) — доверенный,
 *    открывает любое задание по номеру; в списках он «владелец» меток «ui», так же как пишет задания.
 */

/** Метка заданий, поставленных без почты (служебный запрос, режим разработки). */
export const SERVICE_OWNER = "ui";

export interface EstimateViewer {
  /** Почта вошедшего в нижнем регистре; null — служебный запрос без человека. */
  readonly email: string | null;
  readonly admin: boolean;
}

/** Значение `requested_by`, по которому отбираются «мои» задания. */
export function ownerKey(viewer: EstimateViewer): string {
  return viewer.email ?? SERVICE_OWNER;
}

/** Можно ли отдать задание этому зрителю по номеру. Чужое выглядит как несуществующее: ответ один и тот же. */
export function canReadEstimateJob(viewer: EstimateViewer, requestedBy: string | null | undefined): boolean {
  if (viewer.email === null || viewer.admin) return true;
  return typeof requestedBy === "string" && requestedBy.trim().toLowerCase() === viewer.email;
}
