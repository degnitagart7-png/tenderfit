/**
 * Два трека опроса источников: быстрый и медленный.
 *
 * Зачем два. Плановый прогон идёт каждые два часа и опрашивает все площадки
 * сразу, но площадки обходятся по-разному дорого. ЕИС, Сбербанк-АСТ и ТЭК-Торг
 * отдают выдачу одним-двумя запросами. Росэлторг и Фабрикант на каждую
 * процедуру тратят отдельный запрос карточки и добирают лоты страницами: в
 * прогоне 03.10.2026 они заняли 86 секунд из 280, а у хоста документов
 * Фабриканта в robots.txt стоит `Crawl-delay: 3`. Ходить к ним втрое чаще, чем
 * того требует лента, — лишняя нагрузка на чужие площадки и лишние минуты
 * занятого воркера: закупки живут сутками, и свежесть в два часа ленте не нужна.
 *
 * Поэтому быстрый трек идёт на каждом плановом прогоне, а медленный — не чаще
 * раза в `SYNC_SLOW_INTERVAL_HOURS` (по умолчанию 6). Кнопка «Запустить
 * прогон» опрашивает оба: человек просит свежее, и ждать трек ему незачем.
 *
 * Правило сделано по образцу Контур.Закупок (`decideKonturSync`): отсчёт от
 * времени последней записи источника, а не от часа суток. Плановое задание
 * может стоять на нечётных часах, и привязка к «hour % 6» не сработала бы ни
 * разу.
 */

/** Как часто опрашивается медленный трек, если переменная окружения не задана. */
export const DEFAULT_SLOW_TRACK_INTERVAL_HOURS = 6;

/**
 * Допуск: за сколько минут до срока опрос уже считается подошедшим.
 *
 * Запись источника ставится в конце прогона, а следующий плановый запуск
 * отсчитывается от его начала. Прогон идёт до пяти минут, поэтому ровно через
 * три тика по два часа от записи прошло 5 ч 55 мин. Без допуска третий тик
 * пропускался бы на пять минут, и источник опрашивался бы не каждые 6 часов, а
 * каждые 8. Пятнадцать минут перекрывают длину прогона с запасом, а на
 * частоту влияют слабо.
 */
export const TRACK_TOLERANCE_MINUTES = 15;

/**
 * Интервал медленного трека из переменной окружения, часы.
 *
 * Не число и отрицательное значение — значение по умолчанию: опечатка в
 * настройке не должна ни остановить площадки, ни включить их на каждый тик.
 * Ноль — осознанное «трека нет»: все источники идут каждый прогон.
 */
export function slowTrackIntervalHours(raw: string | undefined): number {
  const text = (raw ?? "").trim().replace(",", ".");
  if (text === "") return DEFAULT_SLOW_TRACK_INTERVAL_HOURS;
  const value = Number.parseFloat(text);
  if (!Number.isFinite(value) || value < 0) return DEFAULT_SLOW_TRACK_INTERVAL_HOURS;
  return value;
}

/** Решение «опрашивать ли источник медленного трека в этом прогоне». */
export interface TrackDecision {
  poll: boolean;
  /** Сколько часов прошло с последней записи; null — записей не было. */
  hoursSinceLastStore: number | null;
  /** Причина пропуска для лога прогона; null, если источник опрашиваем. */
  reason: string | null;
}

/** Часы по-русски: запятая как разделитель. */
function formatHours(hours: number): string {
  return (Math.round(hours * 10) / 10).toFixed(1).replace(".", ",");
}

/**
 * Чистая часть правила: опрос нужен, если с последней записи источника прошло
 * не меньше интервала за вычетом допуска.
 *
 * Неизвестное время (записей нет, метка не читается) трактуется как
 * «опрашивать»: лучше лишний обход, чем лента, которая молча перестала
 * пополняться из-за отсутствия данных.
 */
export function decideTrack(input: {
  lastStoredAt: string | null;
  now: string;
  minIntervalHours: number;
}): TrackDecision {
  const open: TrackDecision = { poll: true, hoursSinceLastStore: null, reason: null };
  if (input.minIntervalHours <= 0 || !input.lastStoredAt) return open;

  const last = Date.parse(input.lastStoredAt);
  const now = Date.parse(input.now);
  if (Number.isNaN(last) || Number.isNaN(now)) return open;

  // Метка из будущего (разошлись часы) считается нулём, а не «очень давно»:
  // иначе сбой часов включал бы источник на каждом тике.
  const hours = Math.max(0, (now - last) / 3_600_000);
  const due = input.minIntervalHours - TRACK_TOLERANCE_MINUTES / 60;
  if (hours >= due) return { poll: true, hoursSinceLastStore: hours, reason: null };

  const ago = hours < 1 ? "меньше часа назад" : `${formatHours(hours)} ч назад`;
  return {
    poll: false,
    hoursSinceLastStore: hours,
    reason:
      `медленный трек: источник записывали ${ago}, интервал между опросами — ` +
      `${formatHours(input.minIntervalHours)} ч`,
  };
}

/** Что запустило прогон. */
export type SyncTrigger = "scheduled" | "queued" | "manual";

/**
 * Какие треки опрашивает прогон с таким запуском.
 *
 * `due` — только подошедшие: так идёт плановый тик, и именно на нём медленный
 * трек экономит обходы. `all` — оба трека без проверки интервала: прогон просит
 * человек, нажав кнопку или запустив воркер с `--full-sync`, и ждать окна
 * медленного трека ему незачем. Платный Контур этим выбором не управляется:
 * его частоту держит собственный интервал в любом режиме.
 */
export function tracksFor(trigger: SyncTrigger): "due" | "all" {
  return trigger === "scheduled" ? "due" : "all";
}
