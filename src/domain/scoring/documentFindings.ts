import type { AnalysisFinding } from "@/types/database";

/**
 * Понижение псевдо-блокеров, найденных моделью в документации.
 *
 * Зачем правило в домене, а не только в промпте. Любой блокер с высокой
 * важностью переводит вердикт в NOT_RECOMMENDED (`applyDocumentFindings`), то
 * есть решение об участии зависит от того, как модель назвала находку. Промпт
 * на это влияет, но не гарантирует ничего: формулировку меняют, модель
 * обновляют, и вердикт молча начинает считаться иначе. Здесь — детерминированное
 * правило, которое проверяется тестом.
 *
 * Что оно правит. Живой разбор закупки 32616404800 дал 23 блокера, и настоящих
 * среди них не было ни одного: отсутствие в РНП, отсутствие банкротства,
 * ст. 19.28 КоАП, санкционные перечни, обеспечение заявки, требования к
 * банку-гаранту, обязанности поставщика после заключения договора и ссылки на
 * подразделы приложения без самого требования. Пока читались два документа,
 * этого было не видно; с распаковкой архивов такие условия стали находиться у
 * каждой закупки, и чем полнее документация, тем вернее закупка отсеивалась.
 *
 * Принцип разделения: блокер — это то, **чем участник должен обладать заранее**
 * и что можно сверить с профилем компании: конкретная лицензия, членство в СРО,
 * допуск к гостайне. Такую находку детерминированный движок и так проверяет по
 * профилю (`isRequirementSatisfied`), поэтому оставлять её блокером осмысленно.
 * Всё, что профиль подтвердить или опровергнуть не может, уходит в
 * `requirement` — в том числе аккредитация у конкретного заказчика: она
 * получаема, и молча отказываться от закупки из-за неё нельзя.
 *
 * Находка при этом не пропадает и не переписывается: меняется только категория,
 * цитата и раздел остаются. Пользователь увидит требование в списке и проверит
 * его сам.
 *
 * Порядок проверки важен и обратен читаемому: сперва признаки того, что
 * упомянутая лицензия вообще не про участника, потом признаки настоящего
 * блокера, и только потом типовые условия допуска.
 */

/**
 * Лицензия упомянута, но она не про нашего участника.
 *
 * Эта группа перевешивает `PROFILE_CHECKABLE`, потому что слово «лицензия» в
 * тексте ещё не значит, что лицензию должны предъявить мы. На 32616404800 так
 * прошли требования к банку-гаранту: лицензия ЦБ РФ, рейтинг, размер
 * собственных средств — всё это про банк, а закупка из-за этого получала
 * NOT_RECOMMENDED.
 */
const NOT_PARTICIPANT_CREDENTIAL: readonly RegExp[] = [
  // Банковская гарантия: требования предъявляются банку, а не участнику.
  /банковск[а-яё]*\s*гаранти|банк[-\s]*гарант/i,
  /*
    «Все необходимые допуски, разрешения и лицензии» — формулировка без
    содержания: сверить её не с чем, конкретная лицензия не названа.
  */
  /(все|всех|любы[а-яё]*|необходим[а-яё]*)\s*(допуск|разрешен|лиценз)/i,
];

/** Настоящий блокер: то, чем участник обладает и что сверяется с профилем. */
const PROFILE_CHECKABLE: readonly RegExp[] = [
  /лицензи/i,
  /\bсро\b|саморегулируем/i,
  /гостайн|государственн[а-яё]* тайн/i,
  /допуск[а-яё]* к сведениям/i,
];

/**
 * Признаки типового условия допуска.
 *
 * Список закрытый и ведётся руками: добавлять сюда можно только то, что
 * выполняет любая действующая компания, либо то, что относится не к допуску
 * участника, а к исполнению договора. Общие слова («требование», «участник»)
 * непригодны — они понизили бы настоящие блокеры.
 */
const UNIVERSAL_CONDITIONS: readonly RegExp[] = [
  // Реестр недобросовестных поставщиков — декларируется, проверяется заказчиком.
  /рнп|недобросовестн/i,
  // Состояние юридического лица: ликвидация, банкротство, приостановление.
  /ликвидац/i,
  /банкротств|конкурсн[а-яё]* производств/i,
  /приостановлен[а-яё]* деятельност/i,
  // Налоги, судимость, дисквалификация, коррупционная статья.
  /недоимк|задолженност[а-яё]* по налог/i,
  /судимост/i,
  // Корень один, окончания разные: «дисквалификация» и «дисквалифицирован».
  /дисквалифи/i,
  /19\.28|незаконн[а-яё]* вознагражден/i,
  /*
    Санкции и специальные экономические меры.
    Формулировок много: «в санкционном перечне», «в перечне юридических лиц под
    санкциями», «под специальными экономическими мерами». Проверяется это по
    открытым перечням и к профилю компании отношения не имеет.
  */
  /санкцион[а-яё]*\s*(перечн|списк)/i,
  /под\s*санкци/i,
  /специальн[а-яё]*\s*экономическ[а-яё]*\s*мер/i,
  /офшорн/i,
  /иностранн[а-яё]*\s*агент/i,
  /конфликт[а-яё]*\s*интересов/i,
  /*
    Обеспечение заявки и договора — финансовое условие, а не допуск.
    Его считает Financial Fit по профилю: лимиты обеспечения там заданы числом,
    и дублировать это блокером значит отказываться от закупки дважды за одно.
  */
  /обеспечен[а-яё]*\s*(заявк|исполнен)/i,
  /*
    Аккредитация: и общая на площадке, и у конкретного заказчика.
    Профиль о ней ничего не знает, а получить её можно — поэтому это требование
    к проверке человеком, а не основание отказаться.
  */
  /аккредитац/i,
  /*
    Обязанности на этапе исполнения договора.
    «Поставщик обязан согласовать конструкторскую документацию с Заказчиком» —
    это работа после подписания, а не условие, по которому нас не допустят.
    Такие пункты важны (они остаются требованием), но отсеивать по ним закупку
    нельзя: иначе любой нормальный договор становится стоп-фактором.
  */
  /(поставщик|подрядчик|исполнитель)\s*обязан/i,
  /после\s*заключения\s*договора/i,
  /согласова[а-яё]*\s*(конструкторск|проектн|рабоч|техническ|специфик|расч[её]т)/i,
  /соответствовать\s*(проектн|конструкторск|рабоч|техническ)[а-яё]*\s*документац/i,
  /*
    Ссылка на подраздел вместо самого требования.
    «Участники должны соответствовать специальным требованиям, если они
    установлены в подразделе 8.3» — содержания здесь нет, проверить нечего.
    Модель выдала таких три штуки подряд, и каждая роняла вердикт.
  */
  /если\s+(они|оно|это)\s+установлен/i,
  /требовани[а-яё]*,?\s*установленн[а-яё]*\s+в\s+(подраздел|раздел|пункт|приложени)/i,
];

/**
 * Понижает блокеры, которые на деле являются типовыми условиями допуска.
 *
 * Возвращает новый массив; входной не меняется. Категории, кроме `blocker`, не
 * трогаются вовсе: правило отвечает только за то, что двигает вердикт.
 */
export function demoteUniversalBlockers(
  findings: readonly AnalysisFinding[],
): AnalysisFinding[] {
  return findings.map((finding) => {
    if (finding.category !== "blocker") return finding;

    const text = `${finding.title} ${finding.detail}`;

    const demote = () =>
      ({ ...finding, category: "requirement" }) satisfies AnalysisFinding;

    if (NOT_PARTICIPANT_CREDENTIAL.some((pattern) => pattern.test(text)))
      return demote();

    /*
      Лицензия и СРО перевешивают типовые условия. Формулировка вроде «лицензия
      ФСБ, участник не должен находиться в процессе ликвидации» несёт оба
      признака сразу, и понизить её значило бы потерять настоящий стоп-фактор.
    */
    if (PROFILE_CHECKABLE.some((pattern) => pattern.test(text))) return finding;
    if (!UNIVERSAL_CONDITIONS.some((pattern) => pattern.test(text)))
      return finding;

    return demote();
  });
}
