import { describe, expect, it } from "vitest";

import { demoteUniversalBlockers } from "@/domain/scoring/documentFindings";
import type { AnalysisFinding } from "@/types/database";

function finding(over: Partial<AnalysisFinding> = {}): AnalysisFinding {
  return {
    category: "blocker",
    title: "Требование",
    detail: "Описание требования.",
    evidence_quote: "Цитата из документа",
    evidence_section: "Раздел 5",
    severity: "high",
    ...over,
  };
}

/**
 * Случаи взяты с живого разбора закупки 32616404800: там модель выдала
 * 23 блокера, и настоящих среди них не было почти ни одного. Любой блокер
 * с высокой важностью переводит вердикт в NOT_RECOMMENDED, поэтому закупка с
 * чистой документацией отсеивалась автоматически.
 */
describe("demoteUniversalBlockers", () => {
  const universal = [
    "Отсутствие в реестре недобросовестных поставщиков (РНП)",
    "Непроведение ликвидации участника закупки",
    "Отсутствие процедуры банкротства",
    "Неприостановление деятельности участника",
    "Отсутствие недоимки по налогам и сборам",
    "Отсутствие судимости у руководителя",
    "Руководитель не дисквалифицирован",
    "Участник не привлекался по ст. 19.28 КоАП РФ",
    "Отсутствие в санкционных перечнях",
    "Участник не является иностранным агентом",
    "Отсутствие конфликта интересов с заказчиком",
    "Обеспечение заявки 1 197 455,64 ₽",
    "Обеспечение исполнения договора 10 %",
    "Аккредитация на электронной торговой площадке",
  ];

  it.each(universal)("понижает типовое условие допуска: %s", (title) => {
    const [result] = demoteUniversalBlockers([finding({ title })]);

    expect(result?.category).toBe("requirement");
  });

  it("оставляет блокером лицензию — её наличие проверяется по профилю", () => {
    const [result] = demoteUniversalBlockers([
      finding({
        title: "Лицензия ФСБ на работы со сведениями, составляющими гостайну",
      }),
    ]);

    expect(result?.category).toBe("blocker");
  });

  it("оставляет блокером членство в СРО", () => {
    const [result] = demoteUniversalBlockers([
      finding({ title: "Членство в СРО в области строительства" }),
    ]);

    expect(result?.category).toBe("blocker");
  });

  it("понижает аккредитацию у конкретного заказчика: профиль о ней ничего не знает", () => {
    const [result] = demoteUniversalBlockers([
      finding({ title: "Аккредитация в Группе РусГидро" }),
    ]);

    expect(result?.category).toBe("requirement");
  });

  it("смотрит и в подробность, когда заголовок ничего не говорит", () => {
    const [result] = demoteUniversalBlockers([
      finding({
        title: "Требование к участнику",
        detail:
          "Участник не должен находиться в процессе ликвидации или банкротства.",
      }),
    ]);

    expect(result?.category).toBe("requirement");
  });

  it("не трогает риски и требования", () => {
    const input = [
      finding({ category: "risk", title: "Неустойка 0,5 % в день" }),
      finding({ category: "requirement", title: "Отсутствие в РНП" }),
      finding({ category: "neutral", title: "Срок подачи заявок" }),
    ];

    expect(demoteUniversalBlockers(input).map((item) => item.category)).toEqual(
      ["risk", "requirement", "neutral"],
    );
  });

  it("сохраняет остальные поля находки без изменений", () => {
    const source = finding({ title: "Отсутствие в РНП", severity: "high" });

    const [result] = demoteUniversalBlockers([source]);

    expect(result).toEqual({ ...source, category: "requirement" });
  });

  it("на пустом списке возвращает пустой", () => {
    expect(demoteUniversalBlockers([])).toEqual([]);
  });

  /*
    Дальше — настоящие тексты из тех самых 23 блокеров закупки 32616404800.
    Заголовок и подробность взяты дословно: правило проверяется на том, на чём
    оно сломалось, а не на пересказе.
  */
  const realBlockers: readonly [string, string][] = [
    [
      "Требования к банковской гарантии",
      "Банк-Гарант должен соответствовать критериям, установленным в Приложении № 6 к Договору, включая наличие действующей лицензии ЦБ РФ, присутствие в Перечне кредитных организаций по 213-ФЗ, собственные средства не менее 30 млрд. рублей и кредитный рейтинг не ниже 'А' или 'ruА'.",
    ],
    [
      "Наличие допусков, разрешений и лицензий для оказания услуг",
      "Поставщик обязан обеспечить наличие всех необходимых допусков, разрешений и лицензий для оказания услуг, а также незамедлительно сообщать об их отзыве или приостановлении.",
    ],
    [
      "Согласование конструкторской документации с Заказчиком",
      "Поставщик обязан обеспечить согласование конструкторской документации (заводской документации) с Заказчиком после заключения договора.",
    ],
    [
      "Согласование расчетов металлоконструкций",
      "Поставщик обязан предоставить расчеты металлоконструкций на расчетно-климатические условия и согласовать их с Заказчиком до изготовления здания.",
    ],
    [
      "Соответствие проектной документации",
      "Технические характеристики, габаритные размеры и цветовое решение фасадов здания должны полностью соответствовать проектной документации ПС220-13.21-1-АР, ПС220-13.21-1-КР.",
    ],
    [
      "Обязательные требования к Участникам",
      "Участники должны соответствовать обязательным требованиям, установленным в подразделе 8.2 Приложения № 3.",
    ],
    [
      "Специальные требования к Участникам",
      "Участники должны соответствовать специальным требованиям, если они установлены в подразделе 8.3 Приложения № 3.",
    ],
    [
      "Отсутствие в перечне юридических лиц под санкциями",
      "Сведения об Участнике не должны присутствовать в перечне юридических лиц, в отношении которых применяются специальные экономические меры, утвержденном Постановлением Правительства РФ от 11.05.2022 № 851.",
    ],
    [
      "Применение специальных экономических мер",
      "Участник не должен находиться под специальными экономическими мерами, введенными Указом Президента РФ от 03.05.2022 № 252 и Постановлением Правительства РФ от 11.05.2022 № 851.",
    ],
    [
      "Отсутствие дисквалификации руководителя/главного бухгалтера",
      "Участник должен подтвердить отсутствие административного наказания в виде дисквалификации у руководителя, лица, исполняющего функции единоличного исполнительного органа, или главного бухгалтера.",
    ],
  ];

  it.each(realBlockers)(
    "понижает псевдо-блокер с живого разбора: %s",
    (title, detail) => {
      const [result] = demoteUniversalBlockers([finding({ title, detail })]);

      expect(result?.category).toBe("requirement");
    },
  );

  it("не оставляет ни одного блокера из тех 23", () => {
    const input = realBlockers.map(([title, detail]) =>
      finding({ title, detail }),
    );

    const kept = demoteUniversalBlockers(input).filter(
      (item) => item.category === "blocker",
    );

    expect(kept).toEqual([]);
  });

  /*
    Обратная сторона: правило понижает много, и цена ошибки здесь — пропущенный
    стоп-фактор. Ниже случаи, где блокер обязан остаться блокером.
  */
  const keepAsBlocker: readonly [string, string][] = [
    [
      "Лицензия ФСБ на работы со сведениями, составляющими государственную тайну",
      "Участник должен иметь действующую лицензию ФСБ России на проведение работ с использованием сведений, составляющих государственную тайну.",
    ],
    [
      "Членство в СРО в области строительства",
      "Участник должен быть членом саморегулируемой организации с уровнем ответственности не ниже второго.",
    ],
    [
      "Лицензия на обращение с отходами",
      "Подрядчик обязан иметь лицензию на деятельность по сбору и транспортированию отходов I–IV класса опасности.",
    ],
    [
      "Лицензия Минкультуры",
      "Требуется лицензия на сохранение объектов культурного наследия; участник без неё к закупке не допускается.",
    ],
  ];

  it.each(keepAsBlocker)(
    "оставляет блокером то, что сверяется с профилем: %s",
    (title, detail) => {
      const [result] = demoteUniversalBlockers([finding({ title, detail })]);

      expect(result?.category).toBe("blocker");
    },
  );
});
