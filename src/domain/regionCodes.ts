function wordsOf(raw: string): string[] {
  return raw
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[^а-я]+/g, " ")
    .split(" ")
    .filter((word) => word !== "");
}

/**
 * Регион по названию, как его ввёл человек.
 *
 * Совпадение — по началу слова, а не по подстроке: «омск» не должно находиться
 * в «томская». Регионы с похожими словами («Тюменская область» и её округа,
 * «Нижний Новгород» и «Новгородская область») разведены списком `not`.
 * Не нашлось — null: искать по чужому коду нельзя.
 */
export function regionCodeOf(name: string): Region | null {
  const words = wordsOf(name);
  if (words.length === 0) return null;
  const startsWithAny = (keys: readonly string[]): boolean =>
    keys.some((key) => words.some((word) => word.startsWith(key)));

  const candidates = REGIONS.filter(
    (region) => startsWithAny(region.keys) && !startsWithAny(region.not ?? []),
  );
  if (candidates.length === 0) return null;
  // Если подошло несколько, побеждает тот, чей ключ длиннее: он конкретнее.
  const specificity = (region: Region): number =>
    Math.max(
      ...region.keys.filter((key) => words.some((word) => word.startsWith(key))).map((key) => key.length),
    );
  return [...candidates].sort((a, b) => specificity(b) - specificity(a))[0] ?? null;
}

/**
 * Каноническое название региона по тому, как его ввёл человек.
 *
 * Нужно старым профилям, где регион набран свободным текстом («Калмыкия»):
 * выбор из списка сохраняет каноническое название, а старое значение приводится
 * к нему. Не опознано — значение остаётся как было, а не теряется.
 */
export function canonicalRegionName(name: string): string {
  return regionCodeOf(name)?.name ?? name.trim();
}

/** Регионы списка в каноническом виде, без пустых и повторов. */
export function canonicalRegionNames(names: readonly string[]): string[] {
  const result: string[] = [];
  for (const name of names) {
    const canonical = canonicalRegionName(name);
    if (canonical !== "" && !result.includes(canonical)) result.push(canonical);
  }
  return result;
}

/**
 * Один и тот же регион: по коду, если оба названия опознаны, иначе по подстроке.
 *
 * Сравнение по написанию ломалось на мелочах: «Бурятия» и «Республика Бурятия» —
 * один регион, а «Кемеровская область Кузбасс» (тире съедает чистка запроса) не
 * подстрока «Кемеровская область — Кузбасс».
 */
export function isSameRegion(a: string, b: string): boolean {
  const x = a.trim().toLowerCase();
  const y = b.trim().toLowerCase();
  if (x === "" || y === "") return false;
  const ra = regionCodeOf(x);
  const rb = regionCodeOf(y);
  if (ra !== null && rb !== null) return ra.code === rb.code;
  return x.includes(y) || y.includes(x);
}

/**
 * Проверка «закупка из одного из этих регионов» для фильтра ленты.
 *
 * Разбор названия закупки кэшируется: в ленте тысячи строк, а разных регионов в
 * них — десятки.
 */
export function regionMatcher(wanted: readonly string[]): (region: string) => boolean {
  const names = wanted.map((w) => w.trim()).filter(Boolean);
  const cache = new Map<string, boolean>();
  return (region: string) => {
    const hit = cache.get(region);
    if (hit !== undefined) return hit;
    const result = names.some((name) => isSameRegion(name, region));
    cache.set(region, result);
    return result;
  };
}

export function regionByCode(code: string): Region | null {
  return REGIONS.find((region) => region.code === code) ?? null;
}

/** Код региона в формате КЛАДР, который принимает ЕИС: «03» → «03000000000». */
export function kladrId(code: string): string {
  return `${code}000000000`;
}
