export interface Region {
  /** Код региона, две цифры. */
  code: string;
  /** Каноническое название. */
  name: string;
  /** Начала слов, по которым регион узнаётся в названии, введённом человеком. */
  keys: string[];
  /** Слова, при которых совпадение ложно (другой регион с похожим словом). */
  not?: string[];
}

