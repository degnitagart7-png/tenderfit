import { describe, expect, it } from "vitest";

import { cleanTenderSubject } from "@/domain/subjectCleanup";

/**
 * Предмет закупки без шаблонного текста письма.
 *
 * Коммерческие запросы на Росэлторге приходят письмом: «просим направить
 * технико-коммерческое предложение (далее ТКП) на <ПРЕДМЕТ>. В ТКП просим
 * указать стоимость…». Всё письмо попадало в «название»: в ленте оно
 * нечитаемо, а в поиске его шаблонные фразы («отдельными видами юридических
 * лиц», «юридически обязывающим») давали ложные совпадения по слову
 * «юридические» (разбор ошибки 05.10.2026). Предмет — только то, что после «на».
 */

describe("cleanTenderSubject", () => {
  it("вынимает предмет из письма с запросом ТКП", () => {
    const raw =
      "С целью определения ключевых параметров закупки просим Вас направить технико-коммерческое предложение (далее ТКП) на Замена элементов змеевиков и оребренных прямых участков труб испарителя высокого давления котла-утилизатора зав. № 13307, энергоблока №3 Челябинской ТЭЦ-3. В ТКП просим указать стоимость, сроки выполнения работ. Настоящее письмо направлено в соответствии с Положением о закупках и не является закупкой по смыслу Федерального закона № 223-ФЗ «О закупках товаров, работ, услуг отдельными видами юридических лиц».";

    expect(cleanTenderSubject(raw)).toBe(
      "Замена элементов змеевиков и оребренных прямых участков труб испарителя высокого давления котла-утилизатора зав. № 13307, энергоблока №3 Челябинской ТЭЦ-3",
    );
  });

  it("предмет с «ПАО» и кавычками обрезается по границе предложения, а не по точке в сокращении", () => {
    const raw =
      'С целью определения ключевых параметров закупки просим Вас направить технико-коммерческое предложение (далее ТКП) на Оказание услуг по внутрикорпоративному информационному сопровождению деятельности ПАО "Форвард Энерго" в соответствии с прилагаемым Техническим заданием. В ТКП просим указать стоимость услуг.';

    expect(cleanTenderSubject(raw)).toBe(
      'Оказание услуг по внутрикорпоративному информационному сопровождению деятельности ПАО "Форвард Энерго" в соответствии с прилагаемым Техническим заданием',
    );
  });

  it("обычное название остаётся как есть", () => {
    expect(cleanTenderSubject("Оказание юридических услуг")).toBe("Оказание юридических услуг");
  });

  it("письмо без шаблонной фразы про ТКП не трогается", () => {
    const text = "Просим направить предложение по поставке насосов. Срок подачи — до пятницы.";

    expect(cleanTenderSubject(text)).toBe(text);
  });

  it("пустая строка и пробелы — пустая строка", () => {
    expect(cleanTenderSubject("")).toBe("");
    expect(cleanTenderSubject("   ")).toBe("");
  });

  it("повторный вызов ничего не меняет", () => {
    const once = cleanTenderSubject(
      "С целью определения ключевых параметров закупки просим Вас направить технико-коммерческое предложение (далее ТКП) на Поставку насосов. В ТКП просим указать цену.",
    );

    expect(cleanTenderSubject(once)).toBe(once);
  });

  it("если после «на» ничего нет, возвращается исходный текст", () => {
    const raw = "просим направить технико-коммерческое предложение (далее ТКП) на ";

    expect(cleanTenderSubject(raw)).toBe(raw.trim());
  });
});
