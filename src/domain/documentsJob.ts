import type { SyncJobPayload } from "@/types/database";

/**
 * Что воркер сделает с заданием на документацию.
 *
 * Правила вынесены из `scripts/worker.ts` в чистый домен: от них зависит, будет
 * ли потрачен платный запрос Контур.Закупок и будет ли оплачен разбор моделью,
 * а сам воркер живёт на сервере без репозитория и без тестов. Здесь обе траты
 * видны в тестах, без сети и без базы.
 */

/**
 * Сколько закупок может быть в одном платном задании.
 *
 * Карточка покупается на каждую закупку, которой ЕИС документацию не отдала, а
 * суточный бюджет группы `purchase` — 30 запросов. Предел в 5 оставляет день на
 * плановые поиски и не даёт одному заданию, поставленному по ошибке на массовый
 * список, сжечь бюджет за один тик. Партнёр ставит платное задание нажатием
 * кнопки в карточке одной закупки, поэтому предел в нормальной работе не
 * достигается — он ловит именно ошибку.
 */
export const PAID_CARD_JOB_LIMIT = 5;

export interface DocumentsJobOptions {
  /** Читать платную карточку Контур.Закупок, когда ЕИС документацию не отдала. */
  konturCards: boolean;
  /** Запускать ли AI-разбор сразу после загрузки, а не ждать планового прогона. */
  runWorker: boolean;
  /** Почему платная карточка отключена, хотя задание её просило; null — купит. */
  cardRefusal: string | null;
}

const FREE_JOB: DocumentsJobOptions = {
  konturCards: false,
  runWorker: false,
  cardRefusal: null,
};

/**
 * Задание кнопки «Глубокий анализ»: загрузка бесплатная, разбор — сразу.
 * Разбор уже оплачен решением партнёра: задача создана и суточный лимит
 * проверен до постановки задания, так что плановый прогон ждать незачем.
 */
const ANALYZE_JOB: DocumentsJobOptions = {
  konturCards: false,
  runWorker: true,
  cardRefusal: null,
};

/**
 * Опции загрузки документации по заданию из очереди.
 *
 * Бесплатное задание (документация найденных закупок, которую сервер ставит в
 * очередь после платного поиска, и запуск из панели администратора)
 * намеренно не запускает разбор: номеров в нём десятки, а разбор стоит ≈6 ₽ за
 * закупку при суточном потолке 20. Платное задание наоборот доводит закупку до
 * конца — партнёр согласился заплатить именно за результат, и ждать разбора ещё
 * два часа до планового прогона после покупки карточки было бы обманом.
 */
export function documentsJobOptions(
  payload: SyncJobPayload | null | undefined,
): DocumentsJobOptions {
  if (payload?.konturCards !== true) {
    return payload?.analyze === true ? ANALYZE_JOB : FREE_JOB;
  }

  const count = payload.regNumbers?.length ?? 0;
  if (count > PAID_CARD_JOB_LIMIT) {
    return {
      konturCards: false,
      runWorker: false,
      cardRefusal:
        `Платная карточка Контур.Закупок отключена: ${count} ${tendersWord(count)} ` +
        `в одном задании при пределе ${PAID_CARD_JOB_LIMIT}. Документация запрошена бесплатно.`,
    };
  }

  return { konturCards: true, runWorker: true, cardRefusal: null };
}

/**
 * Слово «закупка» в нужной форме.
 *
 * Своя копия вместо `pluralRu` из утилит: домен не тянет модули форматирования,
 * иначе правило про траты источника оказалось бы связано с оформлением дат.
 */
function tendersWord(count: number): string {
  const lastTwo = Math.abs(count) % 100;
  const lastOne = lastTwo % 10;
  if (lastTwo > 10 && lastTwo < 20) return "закупок";
  if (lastOne > 1 && lastOne < 5) return "закупки";
  if (lastOne === 1) return "закупка";
  return "закупок";
}
