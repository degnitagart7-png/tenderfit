/** Факты об источнике. Бросает ошибку, если значения нет в каталоге. */
export function sourceFacts(source: TenderDataSource): SourceFacts {
  const found = SOURCES.find((s) => s.source === source);
  if (!found) {
    // Не «вернём заглушку»: источник без фактов — это дыра в каталоге, и она
    // должна падать здесь, а не показывать пользователю пустую причину.
    throw new Error(`Источник ${source} не описан в каталоге SOURCES.`);
  }
  return found;
}

/**
 * Источники, документация которых читаема: по ним возможен глубокий разбор.
 *
 * Список отвечает только на вопрос «можно ли разобрать», а не «где взять байты»:
 * за второе отвечает `eisPublishedSources()`. ТЭК-Торг входит сюда и не входит
 * туда — его файлы отдаёт сама площадка.
 */
export function documentationSources(): TenderDataSource[] {
  return SOURCES.filter((s) => s.documents === "bytes").map((s) => s.source);
}

/**
 * Источники, чьи закупки публикуются в ЕИС под тем же номером.
 *
 * По ним загрузчик документации обходит печатную форму и вкладку документов
 * реестра. Остальные источники ищут байты у себя: номер площадки в реестре не
 * находится, а запрос по нему вернул бы чужую закупку или ничего.
 */
export function eisPublishedSources(): TenderDataSource[] {
  return SOURCES.filter((s) => s.publishedInEis).map((s) => s.source);
}

/** Приоритет записи по источникам — для upsertByRegNumber. */
export function sourcePriorities(): Record<TenderDataSource, number> {
  return Object.fromEntries(SOURCES.map((s) => [s.source, s.priority])) as Record<
    TenderDataSource,
    number
  >;
}

/** Что опрашивается, когда профиль не перечислил sources явно. */
export function defaultSources(): TenderDataSource[] {
  return SOURCES.filter((s) => s.byDefault).map((s) => s.source);
}

/**
 * Источники, которые плановый прогон умеет собирать.
 *
 * Кроме демонстрационных данных исключено и ручное добавление: такую закупку
 * приносит владелец файлом, опрашивать для неё нечего.
 */
export function syncableSources(): TenderDataSource[] {
  return SOURCES.filter(isSyncable).map((s) => s.source);
}

/**
 * Бесплатная часть прогона: её кнопка «Найти новые закупки» запускает без
 * расхода тарифа.
 *
 * Возвращаются факты, а не только имена: подпись в интерфейсе печатает
 * `title`, а не код источника, и оба берутся из одной записи каталога. Платный
 * агрегатор сюда не входит по определению `cost`, поэтому отключение подписки
 * не меняет ни состав прогона, ни текст подписи.
 */
export function freeSyncSources(): SourceFacts[] {
  return SOURCES.filter((s) => isSyncable(s) && s.cost === "free");
}

/**
 * Названия бесплатных источников в порядке каталога — для подписей.
 *
 * Строку «ЕИС, ТЭК-Торг, Сбербанк-АСТ, Фабрикант и Росэлторг» печатают экран
 * входа, панель администратора, панель поиска и причина остановки платного
 * источника. Перечень, написанный от руки, устаревал трижды за две недели —
 * каждый раз, когда подключали новую площадку, — поэтому он собирается здесь
 * один раз и из тех же записей каталога, по которым прогон реально опрашивает
 * источники.
 */
export function freeSourceTitles(): string[] {
  return freeSyncSources().map((facts) => facts.title);
}

/** Опрашивает ли прогон этот источник: демо-данные и ручную загрузку — нет. */
function isSyncable(facts: SourceFacts): boolean {
  return facts.source !== "MOCK" && facts.source !== "IMPORT";
}
