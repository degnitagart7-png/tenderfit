import { describe, expect, it } from "vitest";

import { matchCorpus, parseSearchInput, type SearchCorpus } from "@/domain/textSearch";

/**
 * Смысловые слова запроса обязаны встретиться в названии или лотах закупки.
 *
 * Разбор ошибки 05.10.2026. По запросу «юридические услуги» лента показала три
 * закупки без всякого отношения к праву: «услуги» стояло в названии
 * («Оказание услуг по строительному контролю»), а «юридических» нашлось где-то
 * в теле документов (в перечне заказчиков, в примечании к ТКП). Слова запроса
 * складывались по областям: одно — из названия, другое — из документов, и
 * этого хватало. Но «услуги» есть почти в каждом названии и ничего не
 * выражает; закупку определяет смысловое слово, и оно должно стоять там, где
 * говорится, ЧТО закупают, — в названии или в лотах. Упоминание в документах —
 * это не предмет закупки.
 */

function corpus(over: Partial<SearchCorpus>): SearchCorpus {
  return { subject: "", items: "", documents: "", codes: [], ...over };
}

const match = (c: SearchCorpus, query: string, scopes?: Array<"subject" | "items" | "documents">) =>
  matchCorpus(c, parseSearchInput(query), scopes ? { scopes } : {}).matched;

describe("смысловое слово запроса и область поиска", () => {
  it("слово только в теле документов, а «услуги» в названии — не совпадение", () => {
    const c = corpus({
      subject: "Оказание услуг по строительному контролю в период капитального ремонта здания",
      documents: "Заказчик вправе привлечь юридическое сопровождение договора на любом этапе.",
    });

    expect(match(c, "юридические услуги")).toBe(false);
  });

  it("слово в названии — совпадение", () => {
    expect(match(corpus({ subject: "Оказание юридических услуг" }), "юридические услуги")).toBe(true);
  });

  it("слово в лотах — совпадение: лот и есть предмет закупки", () => {
    const c = corpus({ subject: "Закупка услуг для нужд учреждения", items: "Юридическое сопровождение деятельности" });

    expect(match(c, "юридические услуги")).toBe(true);
  });

  it("запрос из одних общих слов («услуги») совпадает по названию, как раньше", () => {
    expect(match(corpus({ subject: "Оказание услуг связи" }), "услуги")).toBe(true);
  });

  it("общее слово может стоять в документах, если смысловое — в названии", () => {
    const c = corpus({ subject: "Юридическое сопровождение", documents: "Исполнитель оказывает услуги в течение года." });

    expect(match(c, "юридические услуги")).toBe(true);
  });

  it("ограничение областью «документы» снимает правило: человек сам просит искать в документах", () => {
    const c = corpus({ subject: "Поставка оборудования", documents: "Соответствие ГОСТ 12345 обязательно." });

    expect(match(c, "ГОСТ 12345", ["documents"])).toBe(true);
  });

  it("правило то же для ключевых слов профиля (группы)", () => {
    const parsed = { ...parseSearchInput(""), anyGroups: [["юридические", "услуги"]] };
    const inBody = corpus({ subject: "Услуги по уборке", documents: "юридическое сопровождение" });
    const inTitle = corpus({ subject: "Юридические услуги для учреждения" });

    expect(matchCorpus(inBody, parsed).matched).toBe(false);
    expect(matchCorpus(inTitle, parsed).matched).toBe(true);
  });

  it("второе смысловое слово может стоять в документах, если первое — в названии", () => {
    const c = corpus({ subject: "Ремонт кровли", documents: "здание детского сада" });

    expect(match(c, "ремонт детского сада")).toBe(true);
  });

  it("ни одно смысловое слово не стоит в названии — не совпадение, сколько бы их ни было в документах", () => {
    const c = corpus({ subject: "Поставка оборудования", documents: "ремонт детского сада, ремонт кровли" });

    expect(match(c, "ремонт детского сада")).toBe(false);
  });

  it("слово в названии заказчика — не предмет закупки: юридический университет не делает ремонт юридической услугой", () => {
    const c = corpus({
      head: "Оказание услуг по строительному контролю в период капитального ремонта здания",
      subject:
        "Оказание услуг по строительному контролю в период капитального ремонта здания\nМОСКОВСКИЙ ГОСУДАРСТВЕННЫЙ ЮРИДИЧЕСКИЙ УНИВЕРСИТЕТ",
    });

    expect(match(c, "юридические услуги")).toBe(false);
  });

  it("но заказчик по-прежнему находится, если смысловое слово есть в предмете", () => {
    const c = corpus({
      head: "Капитальный ремонт общежития",
      subject: "Капитальный ремонт общежития\nМОСКОВСКИЙ ГОСУДАРСТВЕННЫЙ ЮРИДИЧЕСКИЙ УНИВЕРСИТЕТ",
    });

    expect(match(c, "ремонт юридический университет")).toBe(true);
  });

  it("справочно-правовая система — не правовая услуга: «правовое сопровождение» её не находит", () => {
    const sps = corpus({
      head: "Оказание услуг по сопровождению справочно-правовых систем КонсультантПлюс",
      subject: "Оказание услуг по сопровождению справочно-правовых систем КонсультантПлюс",
    });
    const legal = corpus({
      head: "Правовое сопровождение деятельности учреждения",
      subject: "Правовое сопровождение деятельности учреждения",
    });

    expect(match(sps, "правовое сопровождение")).toBe(false);
    expect(match(legal, "правовое сопровождение")).toBe(true);
  });

  it("а тому, кто ищет именно справочно-правовую систему, она находится", () => {
    const sps = corpus({
      head: "Сопровождение справочной правовой системы КонсультантПлюс",
      subject: "Сопровождение справочной правовой системы КонсультантПлюс",
    });

    expect(match(sps, "справочно-правовая система")).toBe(true);
    expect(match(sps, "справочная правовая система")).toBe(true);
  });

  it("«на право заключения договора» — шаблон почти каждой закупки, а не правовая услуга", () => {
    const c = corpus({
      head: "Редукционная документация на право заключения договора на поставку складского оборудования",
      subject: "Редукционная документация на право заключения договора на поставку складского оборудования",
    });

    expect(match(c, "правовое сопровождение")).toBe(false);
    expect(match(c, "правовое оборудование")).toBe(false);
  });

  it("наречие «юридически» (обязывающий, значимый) — не юридическая услуга", () => {
    const c = corpus({
      head: "Поставка насосов",
      subject: "Поставка насосов",
      items: "Предложение не является юридически обязывающим соглашением; оказание услуг по монтажу",
    });

    expect(match(c, "юридические услуги")).toBe(false);
  });

  it("код ОКПД2 по-прежнему подходит без слов в названии", () => {
    const c = corpus({ subject: "Услуги", codes: ["69.10.10.000"] });

    expect(match(c, "69.10")).toBe(true);
  });
});
