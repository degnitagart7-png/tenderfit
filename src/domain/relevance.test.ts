import { describe, expect, it } from "vitest";

import type { Tender } from "@/domain/entities";
import { isRelevantToKeywords } from "@/domain/relevance";

/**
 * Относится ли найденная площадкой закупка к запросу.
 *
 * Площадка отдаёт всё, что показалось ей похожим: по запросу «юридические
 * услуги» ЕИС вернула оценку арестованного имущества, вывоз отходов и питание
 * участников форума (прогон 05.10.2026) — совпало слово «услуги». Сохранять
 * такое нельзя: ложные находки выглядят как работа поиска, которая не работает.
 * Проверка идёт тем же правилом, каким ищет лента, чтобы найденное при сборе
 * не пропадало из ленты и мусор в неё не попадал.
 */

function tender(subject: string, patch: Partial<Tender> = {}): Tender {
  return {
    regNumber: "0123456789012345678",
    externalId: null,
    subject,
    customerName: "Заказчик",
    deliveryAddress: "",
    lots: [],
    requirements: [],
    documents: [],
    okpd2Codes: [],
    ...patch,
  } as unknown as Tender;
}

describe("isRelevantToKeywords", () => {
  it("предмет закупки совпадает с запросом — подходит", () => {
    expect(isRelevantToKeywords(tender("Оказание юридических услуг"), ["юридические услуги"])).toBe(true);
  });

  it("оценка имущества и вывоз отходов по запросу «юридические услуги» не подходят", () => {
    for (const subject of [
      "Оказание услуг по оценке арестованного имущества и имущественных прав в рамках исполнительного производства",
      "Оказание услуг по транспортированию твердых коммунальных отходов",
      "Услуги по организации проживания и питания участников форума",
      "Оказание услуг по открытию возобновляемой кредитной линии",
    ]) {
      expect(isRelevantToKeywords(tender(subject), ["юридические услуги"])).toBe(false);
    }
  });

  it("достаточно подойти под любое из ключевых слов", () => {
    expect(isRelevantToKeywords(tender("Поставка ноутбуков"), ["принтер", "ноутбук"])).toBe(true);
  });

  it("ни одно слово не подошло — не подходит", () => {
    expect(isRelevantToKeywords(tender("Уборка помещений"), ["принтер", "ноутбук"])).toBe(false);
  });

  it("слова запроса меняют форму: основа, а не точное слово", () => {
    expect(isRelevantToKeywords(tender("Услуги по ремонту кровли"), ["ремонт кровли"])).toBe(true);
  });

  it("пустой список слов — проверять нечем, подходит всё", () => {
    expect(isRelevantToKeywords(tender("Что угодно"), [])).toBe(true);
    expect(isRelevantToKeywords(tender("Что угодно"), ["  "])).toBe(true);
  });

  it("письмо с запросом ТКП судится по предмету, а не по шаблонному тексту", () => {
    const letter =
      "С целью определения ключевых параметров закупки просим Вас направить технико-коммерческое предложение (далее ТКП) на Замена змеевиков котла. В ТКП просим указать стоимость. Не является закупкой по смыслу 223-ФЗ «О закупках отдельными видами юридических лиц».";

    expect(isRelevantToKeywords(tender(letter), ["юридические услуги"])).toBe(false);
    expect(isRelevantToKeywords(tender(letter), ["змеевик"])).toBe(true);
  });
});
