import type { CompanyDocumentCategory } from "@/domain/companyFacts/types";

/**
 * Категория документа по названию файла: человек загружает пачку файлов, и выбирать категорию для каждого — лишняя работа.
 * Подсказка, а не приговор: категория остаётся выпадающим списком у каждого документа, а модель всё равно смотрит на содержимое
 * (в запросе сказано, что тип — подсказка). Не угадали — «Прочее».
 *
 * Порядок правил важен: «Реестр контрактов СРО» — это опыт, а не СРО; «Лицензия на технику» — лицензия.
 */
const RULES: [CompanyDocumentCategory, RegExp][] = [
  ["price", /прайс|price|расценк|тариф|каталог цен|стоимост[а-яё]*\s+работ|смет[а-яё]*\s+цен/iu],
  ["experience", /реестр|контракт|договор|(?<![а-яё])акт(?![а-яё])|кс-?[23]|выписк[а-яё]*\s+из\s+еис|исполненн|опыт|справк[а-яё]*\s+об?\s+опыт/iu],
  ["sro", /(?<![а-яё])сро(?![а-яё])|саморегулир|допуск|ностро|ноприз|свидетельств[а-яё]*\s+о\s+допуск/iu],
  ["license", /лиценз/iu],
  ["staff", /штат|кадр|персонал|сотрудник|работник|специалист|(?<![а-яё])нрс(?![а-яё])|удостоверени|аттестат/iu],
  ["equipment", /техник|оборудован|механизм|автопарк|парк\s+машин|(?<![а-яё])спецтехник/iu],
  ["financial", /баланс|отчёт?\s+о\s+финанс|финанс|бухгалт|декларац/iu],
];

export function guessDocumentCategory(fileName: string): CompanyDocumentCategory {
  const name = fileName.replace(/\.[a-z0-9]{2,5}$/iu, "").replace(/[_\-.]+/gu, " ");
  for (const [category, pattern] of RULES) if (pattern.test(name)) return category;
  return "other";
}
