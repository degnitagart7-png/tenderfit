import { describe, expect, it } from "vitest";

import { SCRUB_MASKS, addScrubStats, emptyScrubStats, formatScrubStats, scrubPii, totalScrubStats } from "@/domain/companyFacts/scrubPii";

/**
 * Скруббер ПД: что должно исчезнуть до отправки в модель и, не менее важно, что обязано остаться.
 * Образцы — как в настоящих документах строительной компании: резюме, удостоверения, договоры, реестры контрактов.
 */

const scrub = (text: string, options?: Parameters<typeof scrubPii>[1]) => scrubPii(text, options);

describe("ФИО", () => {
  it("полное ФИО в именительном падеже", () => {
    const r = scrub("Исполнитель: Иванов Иван Иванович, прораб.");
    expect(r.text).toBe("Исполнитель: [ФИО], прораб.");
    expect(r.stats.fio).toBe(1);
  });

  it("падежи отчества: родительный, дательный, творительный", () => {
    expect(scrub("выдано Петрову Сергею Александровичу").text).not.toMatch(/Петров|Сергею|Александровичу/u);
    expect(scrub("с Кузнецовой Ольгой Николаевной заключён договор").text).not.toMatch(/Кузнецов|Николаевн/u);
    expect(scrub("удостоверение Сидоренко Ирины Ильиничны").text).not.toMatch(/Сидоренко|Ильинич/u);
  });

  it("порядок «имя отчество фамилия»", () => {
    const r = scrub("Подписал Сергей Петрович Васильев лично.");
    expect(r.text).toContain("[ФИО]");
    expect(r.text).not.toMatch(/Васильев|Сергей|Петрович/u);
  });

  it("имя и отчество без фамилии", () => {
    expect(scrub("Уважаемый Иван Петрович, направляем акт.").text).toBe("Уважаемый [ФИО], направляем акт.");
  });

  it("фамилия с инициалами в обоих порядках", () => {
    expect(scrub("Директор ООО Иванов И. И.").text).toBe("Директор ООО [ФИО]");
    expect(scrub("Иванов И.И. принял работы").text).toBe("[ФИО] принял работы");
    expect(scrub("начальник участка А. В. Сидоров, главный инженер").text).toBe("начальник участка [ФИО], главный инженер");
    expect(scrub("И.И. Иванов").text).toBe("[ФИО]");
  });

  it("фамилия с одним инициалом — если она похожа на фамилию", () => {
    expect(scrub("Ответственный: Петрова Е.").text).toBe("Ответственный: [ФИО]");
  });

  it("ФИО прописью заглавными (шапка документа)", () => {
    const r = scrub("ИВАНОВ ИВАН ИВАНОВИЧ принят на должность");
    expect(r.text).toBe("[ФИО] принят на должность");
  });

  it("имя из списка и фамилия без отчества (список сотрудников)", () => {
    const r = scrub("Штат: Сергей Морозов, Анна Ковалёва, Дмитрию Смирнову");
    expect(r.text).not.toMatch(/Морозов|Ковалёва|Смирнову/u);
    expect(r.stats.fio).toBe(3);
  });

  it("фамилия после должности без инициалов", () => {
    const r = scrub("В лице генерального директора Петрова действующего на основании Устава");
    expect(r.text).not.toContain("Петрова");
    expect(r.text).toContain("[ФИО]");
  });

  it("несколько человек в одной строке считаются по отдельности", () => {
    const r = scrub("Иванов И. И., Петров П. П. и Сидоров С. С. подписали акт.");
    expect(r.stats.fio).toBe(3);
  });
});

describe("ФИО: ложные срабатывания", () => {
  const keep = (text: string): void => {
    const r = scrub(text);
    expect(r.text, text).toBe(text);
    expect(r.stats.fio, text).toBe(0);
  };

  it("названия организаций в кавычках после организационно-правовой формы", () => {
    keep("ООО «Сибирская Строительная Компания» выполнило работы");
    keep("Общество с ограниченной ответственностью «Омск Строй Проект»");
    keep("АО «Иван Петрович и сыновья»");
  });

  it("«Приложение А.», «Раздел Б.», литеры и корпуса", () => {
    keep("См. Приложение А. Технические требования");
    keep("Раздел Б. Условия оплаты");
    keep("Здание, лит. А. Корпус 2");
    keep("Таблица Н. Объёмы работ");
  });

  it("улицы, школы и музеи имени кого-то", () => {
    keep("г. Омск, ул. А. Невского, д. 5");
    keep("МБОУ СОШ им. А. С. Пушкина");
    keep("Проспект Карла Маркса, 10");
  });

  it("законы, ведомства, регионы и должности без имён", () => {
    keep("Федеральный закон от 05.04.2013 № 44-ФЗ");
    keep("Министерство строительства Омской области");
    keep("Генеральный директор подписывает договор");
    keep("Главный инженер проекта назначается приказом");
    keep("Заказчик вправе отказаться от Исполнителя");
  });

  it("слова на «-ин», «-ов», которые не фамилии, вне связки с именем и инициалами", () => {
    keep("Магазин строительных материалов, Корпус");
    keep("Центральный Район Омска");
  });

  it("город и область с заглавных", () => {
    keep("Санкт-Петербург, Ленинградская область, Республика Татарстан");
  });
});

describe("телефоны и почта", () => {
  it("телефон в разных записях", () => {
    for (const phone of [
      "+7 913 123-45-67",
      "8 (913) 123-45-67",
      "+7(913)1234567",
      "89131234567",
      "8-913-123-45-67",
    ]) {
      const r = scrub(`Связь: ${phone}, звонить с 9 до 18`);
      expect(r.text, phone).toBe("Связь: [телефон], звонить с 9 до 18");
      expect(r.stats.phone, phone).toBe(1);
    }
  });

  it("городской номер с кодом в скобках и по метке «тел.»", () => {
    expect(scrub("тел. (3812) 21-45-67").text).toContain("[телефон]");
    expect(scrub("Тел.: 21-45-67").text).toBe("Тел.: [телефон]");
    expect(scrub("Факс 8 (3812) 21-45-68").text).not.toMatch(/21-45/u);
  });

  it("электронная почта", () => {
    const r = scrub("Пишите на ivan.petrov@stroy-omsk.ru или info@firma.com");
    expect(r.text).toBe("Пишите на [email] или [email]");
    expect(r.stats.email).toBe(2);
  });

  it("суммы, номера закупок и реквизиты юрлица не принимаются за телефон", () => {
    const text = "Сумма 8 500 000,00 руб., закупка 0373100012826000123, ОГРН 1025500123456, КПП 550101001, р/с 40702810900000012345";
    expect(scrub(text).text).toBe(text);
  });
});

describe("паспорт, СНИЛС, ИНН, дата рождения, адрес", () => {
  it("паспорт с серией и номером", () => {
    expect(scrub("паспорт 52 15 123456").text).toBe("[паспорт]");
    expect(scrub("Паспорт РФ серия 5215 № 123456").text).toContain("[паспорт]");
    expect(scrub("серия 5215 номер 123456").text).toBe("[паспорт]");
  });

  it("паспорт с кем и когда выдан", () => {
    const r = scrub("Паспорт 5215 123456, выдан ОУФМС России по Омской области в Кировском АО г. Омска 12.05.2015 г., код подразделения 550-001. Далее текст.");
    expect(r.text).toBe("[паспорт]. Далее текст.");
    expect(r.stats.passport).toBe(1);
  });

  it("лицензия «выдана» органом — деловой факт, остаётся", () => {
    const text = "Лицензия МЧС № 12345 выдана Главным управлением МЧС России 12.05.2020 сроком на 5 лет";
    expect(scrub(text).text).toBe(text);
  });

  it("СНИЛС с разделителями и по метке", () => {
    expect(scrub("СНИЛС 123-456-789 01").text).toBe("СНИЛС [СНИЛС]".replace("СНИЛС [СНИЛС]", "СНИЛС [СНИЛС]"));
    expect(scrub("СНИЛС: 12345678901").text).toContain("[СНИЛС]");
    expect(scrub("СНИЛС: 12345678901").text).not.toContain("12345678901");
  });

  it("ИНН физлица скрывается, ИНН юрлица остаётся", () => {
    expect(scrub("ИНН 550312345678").text).toBe("ИНН [ИНН физлица]");
    expect(scrub("ИНН: 5503123456, КПП 550301001").text).toBe("ИНН: 5503123456, КПП 550301001");
  });

  it("ИНН самой компании остаётся, даже если это двенадцатизначный ИНН ИП", () => {
    const r = scrub("ИП, ИНН 550312345678; субподрядчик ИНН 770412345678", { companyInn: "550312345678" });
    expect(r.text).toBe("ИП, ИНН 550312345678; субподрядчик ИНН [ИНН физлица]");
    expect(r.stats.personalInn).toBe(1);
  });

  it("дата рождения по метке и по «г. р.»", () => {
    expect(scrub("Дата рождения: 12.05.1980").text).toBe("Дата рождения: [дата рождения]");
    expect(scrub("родился 12 мая 1980 года в г. Омске").text).toBe("родился [дата рождения] в г. Омске");
    expect(scrub("инженер, 1985 г.р.").text).toBe("инженер, [дата рождения]");
    expect(scrub("прораб (1979 года рождения)").text).toBe("прораб ([дата рождения])");
  });

  it("даты договоров и актов остаются", () => {
    const text = "Договор от 12.05.2020, акт № 5 от 01.06.2020, работы выполнены в 2021 году, срок до 2026 г.";
    expect(scrub(text).text).toBe(text);
  });

  it("«2020 года работы» не принимается за год рождения", () => {
    const text = "За 2020 года работы выполнены в срок";
    expect(scrub(text).text).toBe(text);
  });

  it("личный адрес по метке скрывается, адрес организации остаётся", () => {
    const r = scrub("Зарегистрирован по адресу: г. Омск, ул. Ленина, д. 5, кв. 3, именуемый далее Работник.");
    expect(r.text).toBe("Зарегистрирован по адресу: [адрес], именуемый далее Работник.");
    expect(r.stats.address).toBe(1);
    const company = "Юридический адрес: 644000, г. Омск, ул. Ленина, д. 5, офис 301";
    expect(scrub(company).text).toBe(company);
  });

  it("адрес проживания до конца строки", () => {
    const r = scrub("Проживает по адресу: г. Омск, пр. Мира, 10-15\nСледующая строка остаётся");
    expect(r.text).toBe("Проживает по адресу: [адрес]\nСледующая строка остаётся");
  });
});

describe("устройство скруббера", () => {
  it("название компании и ИП из профиля не трогается (keep)", () => {
    const text = "ИП Иванов Иван Иванович, ИНН 550312345678. Директор Иванов И. И. подписал акт.";
    const r = scrub(text, { companyInn: "550312345678", keep: ["ИП Иванов Иван Иванович"] });
    expect(r.text).toContain("ИП Иванов Иван Иванович");
    expect(r.text).toContain("ИНН 550312345678");
    expect(r.text).toContain("Директор [ФИО] подписал");
  });

  it("повторный прогон по очищенному тексту ничего не меняет", () => {
    const raw =
      "Иванов Иван Иванович, тел. +7 913 123-45-67, ivan@mail.ru, паспорт 5215 123456, ИНН 550312345678, 1980 г.р., зарегистрирован по адресу: г. Омск, ул. Мира, 1.";
    const once = scrub(raw);
    const twice = scrub(once.text);
    expect(twice.text).toBe(once.text);
    expect(twice.total).toBe(0);
  });

  it("считает по категориям и форматирует для показа", () => {
    const r = scrub("Иванов И. И., +7 913 123-45-67, a@b.ru, Петров П. П.");
    expect(r.stats).toMatchObject({ fio: 2, phone: 1, email: 1 });
    expect(r.total).toBe(4);
    expect(formatScrubStats(r.stats)).toBe("ФИО: 2, телефонов: 1, адресов почты: 1");
    expect(formatScrubStats(emptyScrubStats())).toBe("");
  });

  it("складывает счётчики", () => {
    const sum = addScrubStats({ ...emptyScrubStats(), fio: 2 }, { ...emptyScrubStats(), fio: 1, phone: 4 });
    expect(sum.fio).toBe(3);
    expect(totalScrubStats(sum)).toBe(7);
  });

  it("пустая строка и текст без личного не меняются", () => {
    expect(scrub("").total).toBe(0);
    const text = "Выполнен капитальный ремонт кровли, сумма контракта 12 450 000 руб., заказчик — Администрация города.";
    expect(scrub(text).text).toBe(text);
  });

  it("метки не совпадают с правилами", () => {
    for (const mask of Object.values(SCRUB_MASKS)) expect(scrub(mask).text).toBe(mask);
  });

  it("резюме: все личные данные уходят, опыт остаётся", () => {
    const resume = [
      "РЕЗЮМЕ",
      "Сидоров Алексей Петрович",
      "Дата рождения: 03.11.1984",
      "Телефон: +7 (913) 555-12-34, e-mail: sidorov84@mail.ru",
      "Адрес места жительства: г. Омск, ул. 70 лет Октября, д. 12, кв. 40",
      "Опыт работы: главный инженер, руководил капитальным ремонтом школы на 48 млн руб. (2023), строительством склада 120 млн руб. (2022).",
      "Удостоверение о повышении квалификации выдано 15.03.2021 (НОСТРОЙ, специалист по организации строительства).",
    ].join("\n");
    const r = scrub(resume);
    expect(r.text).not.toMatch(/Сидоров|Алексей|555|sidorov84|70 лет|03\.11\.1984/u);
    expect(r.text).toContain("48 млн руб.");
    expect(r.text).toContain("120 млн руб.");
    expect(r.text).toContain("НОСТРОЙ");
    expect(r.text).toContain("15.03.2021");
  });

  it("реестр контрактов: заказчики и суммы остаются, подписанты уходят", () => {
    const registry = [
      "№ 3550312345 24 000012 | Администрация Кировского административного округа г. Омска | капитальный ремонт кровли | 12 450 000,00 | 2024",
      "Контакт заказчика: Сергеева Н. А., тел. 8 (3812) 22-33-44",
      "Исполнитель: ООО «СтройОмск», в лице директора Кузнецова А.П.",
    ].join("\n");
    const r = scrub(registry);
    expect(r.text).toContain("Администрация Кировского административного округа г. Омска");
    expect(r.text).toContain("12 450 000,00");
    expect(r.text).toContain("ООО «СтройОмск»");
    expect(r.text).not.toMatch(/Сергеева|22-33-44|Кузнецова/u);
  });

  it("быстро справляется с большим текстом", () => {
    const chunk = "Выполнен ремонт кровли на сумму 12 450 000 руб. Исполнитель Иванов И. И. Тел. +7 913 123-45-67.\n";
    const big = chunk.repeat(5000);
    const started = Date.now();
    const r = scrub(big);
    expect(Date.now() - started).toBeLessThan(5000);
    expect(r.stats.fio).toBe(5000);
    expect(r.stats.phone).toBe(5000);
  });
});

describe("граничные случаи", () => {
  it("адрес не съедает следующее предложение", () => {
    expect(scrub("Работник проживает по адресу: г. Омск, ул. Ленина 5 кв 4. Работник принят.").text).toBe(
      "Работник проживает по адресу: [адрес]. Работник принят.",
    );
  });

  it("паспорт и адрес подряд — оба скрыты, текст между ними цел", () => {
    expect(scrub("Зарегистрирован по адресу: г. Омск, ул. Мира, д. 3, кв. 4. Паспорт 5215 123456.").text).toBe(
      "Зарегистрирован по адресу: [адрес]. [паспорт].",
    );
  });

  it("кем выдан паспорт уходит вместе с номером", () => {
    expect(scrub("паспорт гражданина РФ 5215 123456 выдан 12.05.2015 УМВД России по Омской области. Далее текст").text).toBe(
      "[паспорт]. Далее текст",
    );
  });

  it("фамилия без типичного окончания рядом с именем и отчеством", () => {
    expect(scrub("Мельник Иван Иванович прошёл обучение").text).toBe("[ФИО] прошёл обучение");
  });

  it("глагол перед именем и отчеством не принимается за фамилию", () => {
    expect(scrub("Подписал Иван Петрович договор").text).toBe("Подписал [ФИО] договор");
    expect(scrub("Подписал Сергей Петрович Васильев лично.").text).toBe("Подписал [ФИО] лично.");
  });

  it("ответственный с тире и двоеточием", () => {
    expect(scrub("Ответственный за пожарную безопасность — Орлов").text).toBe("Ответственный за пожарную безопасность — [ФИО]");
  });

  it("ИП в тексте без keep: ФИО предпринимателя скрывается, ИНН чужой тоже", () => {
    const r = scrub("ИП Петров Пётр Петрович (ИНН 550312345678) оказал услуги");
    expect(r.text).toBe("ИП [ФИО] (ИНН [ИНН физлица]) оказал услуги");
  });
});

