/**
 * Предмет закупки без шаблонного текста письма.
 *
 * Коммерческие запросы на Росэлторге приходят письмом: «просим направить
 * технико-коммерческое предложение (далее ТКП) на <ПРЕДМЕТ>. В ТКП просим
 * указать стоимость…». Всё письмо попадало в «название» закупки: в ленте оно
 * нечитаемо, а в поиске его шаблонные фразы («отдельными видами юридических
 * лиц», «юридически обязывающим») давали ложные совпадения по слову
 * «юридические» (разбор ошибки 05.10.2026). Предмет — только то, что после «на».
 *
 * Функция чистая и идемпотентная: применять её можно и при сборе, и при
 * показе, и при поиске, результат один.
 */

/** «…(далее ТКП) на » — после этой фразы начинается предмет. */
const TKP_LEAD = /\(\s*далее\s*[-–—]?\s*ТКП\s*\)\s+на\s+/i;

/**
 * Где кончается предмет: на начале шаблонного предложения письма. Точка в
 * сокращении («ПАО "Х"», «зав. № 5») границей не считается: после неё должно
 * идти одно из типовых начал.
 */
const TKP_TAIL =
  /\.\s+(?:В\s+ТКП|Просим|Стороны|Настоящ|С\s+техническим|По\s+техническим|Для\s+участия|Направляя|Срок|ТКП|Предложение)/;

export function cleanTenderSubject(raw: string): string {
  const text = raw.trim();
  const lead = TKP_LEAD.exec(text);
  if (lead === null) return text;

  const rest = text.slice(lead.index + lead[0].length);
  const tail = TKP_TAIL.exec(rest);
  const subject = (tail === null ? rest : rest.slice(0, tail.index)).trim().replace(/\.$/, "").trim();
  return subject === "" ? text : subject;
}
