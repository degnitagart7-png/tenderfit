/**
 * Статьи раздела «Полезное» (/poleznoe).
 *
 * Зачем раздел. Промо-страница одна и отвечает на один вопрос — «что это за
 * сервис». Подрядчик ищет другое: «срок оплаты по 44-ФЗ», «как проверить смету
 * заказчика», «нужно ли СРО до 10 млн». Статьи под такие запросы приводят его
 * из обычного поиска и из ответов ИИ-ассистентов, которые цитируют страницы с
 * ясной структурой: заголовки, списки, таблицы, вопросы и ответы.
 *
 * Статья — данные, а не разметка: так её проверяет тест (длина описания, связи,
 * вопросы), а страница, карта сайта и llms.txt строятся из одного источника.
 *
 * Строчная разметка внутри текста — только две конструкции:
 *   **жирный** и [текст ссылки](/poleznoe/slug) или (https://…).
 */

export type ArticleCluster = "search" | "documents" | "estimate" | "participation";

export type ArticleBlock =
  /** Абзац. */
  | { type: "p"; text: string }
  /** Раздел статьи; id — якорь для оглавления (латиница, через дефис). */
  | { type: "h2"; text: string; id: string }
  | { type: "h3"; text: string }
  | { type: "ul"; items: string[] }
  | { type: "ol"; items: string[] }
  /** Таблица: заголовки колонок и строки той же длины. */
  | { type: "table"; caption?: string; head: string[]; rows: string[][] }
  /** Выделенная врезка: пример, предупреждение, норма закона. */
  | { type: "note"; title?: string; text: string }
  /** Блок с предложением попробовать сервис; текст необязателен (есть стандартный). */
  | { type: "cta"; text?: string };

export interface ArticleFaq {
  q: string;
  /** Ответ одним-тремя предложениями: его целиком цитируют поисковики и ИИ. */
  a: string;
}

export interface ArticleSource {
  title: string;
  url?: string;
}

export interface Article {
  /** Адрес: /poleznoe/<slug>. Латиница, цифры, дефисы. */
  slug: string;
  cluster: ArticleCluster;
  /** <title> до 65 знаков, главный запрос ближе к началу. */
  title: string;
  /** Заголовок страницы; может быть длиннее title. */
  h1: string;
  /** meta description 120–160 знаков: ответ на запрос, а не реклама. */
  description: string;
  /** Семантическое ядро статьи: первый — главный запрос, дальше — сопутствующие. */
  keywords: string[];
  /** ISO-дата первой публикации и последней правки. */
  published: string;
  updated: string;
  /** Вступление 2–4 предложения: сразу ответ на главный вопрос. */
  lead: string;
  blocks: ArticleBlock[];
  /** 3–5 вопросов: идут в разметку FAQPage. */
  faq: ArticleFaq[];
  /** Слаги 2–4 связанных статей. */
  related: string[];
  /** Нормативные акты и источники данных. */
  sources: ArticleSource[];
}
