-- 20261015000024_notifications.sql
-- Письма: утренняя сводка и «готов анализ / смета».
--
-- Решение владельца 15.10.2026: сводка приходит утром (по умолчанию 08:00 по
-- часовому поясу клиента), а тому, кто запустил глубокий анализ или смету, — письмо,
-- когда расчёт готов. Каждый отключает их у себя в «Уведомлениях».
--
-- `app_users.digest_sent_at` — когда воркер последний раз обработал сводку этого
-- человека (отправил или решил, что сообщить нечего). Отсюда считается «новое с
-- прошлой сводки» и «сегодня уже было».
--
-- `analysis_jobs.notified_at`, `sync_jobs.notified_at` — отметка «по этой задаче с
-- письмом разобрались»: отправлено, либо не нужно (расчёт был коротким, человек
-- отключил письма). Нужна, чтобы письмо по задаче ушло один раз.
--
-- Все колонки необязательные: старые строки остаются с NULL, а воркер не рассылает
-- по ним ничего (письмо о готовности — только по задачам младше 30 минут).
--
-- Миграция идемпотентна: повторный запуск ничего не ломает.
--
-- ПРИМЕНЯТЬ ЧЕРЕЗ SQL EDITOR ДО ВЫКЛАДКИ КОДА: Supabase CLI в этом проекте не работает.

alter table public.app_users add column if not exists digest_sent_at timestamptz;

alter table public.analysis_jobs add column if not exists notified_at timestamptz;

alter table public.sync_jobs add column if not exists notified_at timestamptz;
