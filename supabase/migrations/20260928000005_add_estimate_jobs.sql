-- 20260928000005_add_estimate_jobs.sql
-- Расчёт сметы как задание воркера.
--
-- Зачем через очередь, а не прямым вызовом из прода. Расчёт читает базу
-- ФСНБ-2022 с диска: 56 242 нормы и справочники цен, около 600 МБ памяти и две
-- секунды на загрузку. Каталог индекса исключён из поставки намеренно — 200 МБ
-- справочников не помещаются в серверную функцию Vercel, — поэтому считать
-- может только машина, где эта база лежит: сервер воркера. Отдельного протокола
-- между Vercel и сервером нет, общее у них — эта таблица.
--
-- Второе соображение — время. Извлечение ведомости идёт через модель,
-- фрагментами по 100 тыс. знаков, и на полной документации занимает минуты.
-- Серверная функция столько не живёт, а очередь для того и сделана: кнопка
-- ставит задание и отпускает пользователя, результат приходит сам.
--
-- Новой таблицы не заводим: sync_jobs уже умеет попытки, захват задания
-- воркером, возврат зависших и отчёт. Две очереди рядом расходились бы в
-- поведении при первом же сбое.
--
-- ПРИМЕНЯТЬ ЧЕРЕЗ SQL EDITOR: Supabase CLI в этом проекте не работает.
-- Проект zeypawygxijctavhasyn (Stockholm).
-- Зависит от 20260925000004_add_sync_jobs.sql — применяйте по порядку.

-- ====================== 1. Новый вид задания ======================

alter table public.sync_jobs
  drop constraint if exists sync_jobs_kind_check;

alter table public.sync_jobs
  add constraint sync_jobs_kind_check
  check (kind in ('documents', 'full_sync', 'estimate'));

comment on column public.sync_jobs.kind is
  '''documents'' — догрузить документацию; ''full_sync'' — полный прогон источников; ''estimate'' — посчитать смету по документации закупки или по присланным текстам.';

-- ====================== 2. Индекс под опрос результата ======================

-- Экран опрашивает состояние своего задания по идентификатору, но карточка
-- закупки при открытии ищет последнюю смету по номеру закупки. Без индекса это
-- полный проход по растущей таблице на каждом открытии карточки.
create index if not exists sync_jobs_estimate_tender_idx
  on public.sync_jobs ((payload ->> 'tenderId'), created_at desc)
  where kind = 'estimate';

comment on table public.sync_jobs is
  'Очередь заданий для воркера с российским IP: документация закупок, внеплановые прогоны и расчёт сметы. Ставится продом на Vercel, выполняется scripts/worker.ts.';
