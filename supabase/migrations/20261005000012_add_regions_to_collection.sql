-- Регион в плановом сборе: профили сервера и спрос посетителей.
--
-- Зачем: живой поиск уже искал закупки по региону заказчика (ЕИС принимает код
-- региона), а плановый сбор шёл по всей России. Региональная компания получала в
-- базе единицы своих закупок: по Бурятии нашлась одна из 849. Теперь регионы
-- профиля и регионы, в которых посетитель ждёт тему, доходят до сборщика.
--
-- Пустой массив = вся Россия, поэтому у существующих строк поведение прежнее.
-- Код тоже работает без этой миграции: профили и спрос сохраняются без регионов,
-- пока колонок нет.
--
-- ПРИМЕНЯТЬ ЧЕРЕЗ SQL EDITOR: Supabase CLI в этом проекте не работает.
-- Зависит от миграций 20261004000009 (sync_profiles) и 20261005000010 (search_demand).

alter table public.sync_profiles
  add column if not exists regions text[] not null default '{}';

alter table public.search_demand
  add column if not exists regions text[] not null default '{}';
