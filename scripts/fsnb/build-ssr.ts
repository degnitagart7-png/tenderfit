function main(): void {
  mkdirSync(APP_COPY_DIR, { recursive: true });
  const write = (name: string, data: unknown): void => {
    const text = `${JSON.stringify(data, null, 2)}\n`;
    writeFileSync(resolve(OUTPUT_DIR, name), text, "utf8");
    writeFileSync(resolve(APP_COPY_DIR, name), text, "utf8");
  };
  const ssr = buildSsr();
  const deflators = buildForecastDeflators();
  write("ssr.json", ssr);
  write("forecast-deflators.json", deflators);
  console.log(
    `ssr: ${String(ssr.chapters.length)} глав, резерв ${ssr.reserve.rates.map((rate) => `${String(rate.percent)} %`).join(" / ")}; ` +
      `дефляторы: ${deflators.years.map((item) => String(item.year)).join(", ")} (письмо от ${deflators.letter.date})`,
  );
}

