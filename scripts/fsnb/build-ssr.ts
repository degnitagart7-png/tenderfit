export function readSource(file: string): string {
  return readFileSync(resolve(SOURCES_DIR, file), "utf8");
}

/**
 * Текст источника, свёрнутый для поиска: без строк постраничной печати (`=== стр. N ===`, `=== p….png`)
 * и без различий в пробелах и переносах.
 */
export function squashedSource(file: string): string {
  return readSource(file)
    .split("\n")
    .filter((line) => !/^=== (?:стр\. \d+|p\S+\.png) ===$/u.test(line.trim()) && !/^=== p\S+\/p-\d+\.png$/u.test(line.trim()))
    .join(" ")
    .replace(/\s+/gu, " ");
}

export function squash(value: string): string {
  return value.replace(/\s+/gu, " ").trim();
}

const cache = new Map<string, string>();
function squashedCached(file: string): string {
  const hit = cache.get(file);
  if (hit !== undefined) return hit;
  const text = squashedSource(file);
  cache.set(file, text);
  return text;
}

/** Фрагмент обязан стоять в тексте источника; иначе сборка падает. */
export function cite(file: string, ref: string, fragment: string): SsrCitation {
  if (!squashedCached(file).includes(squash(fragment))) {
    throw new Error(`Фрагмент не найден в ${file} (${ref}): «${fragment.slice(0, 120)}»`);
  }
  return { file, ref, fragment: squash(fragment) };
}

