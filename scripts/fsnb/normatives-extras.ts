const REST =
  /^(?:остальная территория(?! Таймырского)|вся территория, за исключением|территория, за исключением указанных ниже)/iu;

export function finalizeZoneParts(drafts: readonly ZoneDraft[]): WinterZonePart[] {
  return drafts.map((draft) => ({
    id: `A4-${draft.item}`,
    item: draft.item,
    subject: draft.subject,
    description: draft.description,
    zone: draft.zone,
    winterStart: draft.winterStart,
    winterEnd: draft.winterEnd,
    coefficient: draft.coefficient,
    rest: REST.test(draft.description),
    // Субъект без частей и часть, названная списком: единицы нужны только последним.
    units: UNITS_BY_ITEM[draft.item] ?? [],
    fragment: draft.fragment,
  }));
}

